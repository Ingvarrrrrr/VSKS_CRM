export interface RegionOkatoInfo {
  /** Префикс ОКАТО субъекта (2 или 5 цифр; до 11 добивается нулями на backend) */
  okato: string
  /** Федеральный округ */
  district: string
}

/** Нормализация строки региона: casefold, ё→е, тире→дефис, пробелы схлопнуть */
function _norm(s: string): string {
  return s
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[\u2013\u2014\u2212\u00ad]/g, '-')
    .replace(/\s+/g, ' ')
}

