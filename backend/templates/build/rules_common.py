# Regexp для поиска «НДС, 18%» в ячейках таблицы итогов
_VAT_18_RE = re.compile(r"НДС,\s*18%")

XML_NS = "http://www.w3.org/XML/1998/namespace"


def _set_cell_text(cell, text: str) -> None:
    """Заменяет содержимое первого параграфа ячейки на text (один run)."""
    from lxml import etree
    _W = f"{{{W}}}"
    ns = {"w": W}
    # Берём первый (и обычно единственный) параграф ячейки
    para = cell.find("w:p", ns)
    if para is None:
        para = etree.SubElement(cell, f"{_W}p")

    # Сохраняем pPr (форматирование) если есть
    ppr = para.find("w:pPr", ns)

    # Чистим все дочерние элементы, кроме pPr
    for child in list(para):
        if child.tag != f"{_W}pPr":
            para.remove(child)

    if text:
        r = etree.SubElement(para, f"{_W}r")
        t = etree.SubElement(r, f"{_W}t")
        t.text = text
        if text and (text[0] == " " or text[-1] == " "):
            t.set(f"{{{XML_NS}}}space", "preserve")


def _make_tag_row(template_row, tag_text: str):
    """
    Клонирует строку таблицы и ставит tag_text в первую ячейку,
    остальные ячейки очищает. Возвращает новый элемент <w:tr>.

    docxtpl обрабатывает строку вида:
      <w:tr> ... <w:t>{%tr for x in xs %}</w:t> ... </w:tr>
    и заменяет весь <w:tr> на {% for x in xs %}.
    Аналогично для {%tr endfor %}.
    """
    import copy
    from lxml import etree
    _W = f"{{{W}}}"
    ns = {"w": W}

    new_row = copy.deepcopy(template_row)
    cells = new_row.findall("w:tc", ns)
    if not cells:
        return new_row

    # Первая ячейка — помещаем тег
    _set_cell_text(cells[0], tag_text)
    # Остальные ячейки — очищаем
    for cell in cells[1:]:
        _set_cell_text(cell, "")

    return new_row


def apply_t4_repair_tables(root, counts: dict) -> None:
    """
    T4: разворачивает сметные таблицы шаблона contract_repair_framework в {%tr for %} циклы.

    По семантике docxtpl:
      - строка <w:tr> содержащая {%tr for x in xs %} заменяется на {% for x in xs %}
      - строка <w:tr> содержащая {%tr endfor %}      заменяется на {% endfor %}

    Структура после преобразования (одна таблица работ, одна запчастей):
      <header row>              — шапка без изменений
      <for-tag row>            — {%tr for item in items %}
      <data row>               — {{ item.name }}, {{ item.quantity }}, ...
      <endfor-tag row>         — {%tr endfor %}

    - Таблица 3 (работы): Код | Наименование Работ | Кол-во | Норма н/ч | Стоимость | Сумма
    - Таблица 4 (запчасти): Код | Наименование | Ед.измер. | Кол-во | Стоимость | Сумма
    - Таблица 5 (итоги): заменяет зашитую «НДС, 18%» на «НДС, {{ vat_rate }}%»
    """
    from lxml import etree
    ns = {"w": W}
    tables = root.findall(".//w:tbl", ns)

    if len(tables) < 6:
        return  # не repair_framework, пропускаем

    # ── Таблица работ (index 3) ──────────────────────────────────────────────
    t3 = tables[3]
    t3_rows = t3.findall("w:tr", ns)
    if len(t3_rows) >= 2:
        data_row = t3_rows[1]
        cells = data_row.findall("w:tc", ns)
        if len(cells) == 6:
            # Вставляем строку-тег FOR перед строкой данных
            for_row = _make_tag_row(data_row, "{%tr for item in items %}")
            t3.insert(list(t3).index(data_row), for_row)

            # Заполняем строку данных
            _set_cell_text(cells[0], "{{ item.code }}")
            _set_cell_text(cells[1], "{{ item.name }}")
            _set_cell_text(cells[2], "{{ item.quantity }}")
            _set_cell_text(cells[3], "{{ item.norm_hours }}")
            _set_cell_text(cells[4], "{{ item.unit_price }}")
            _set_cell_text(cells[5], "{{ item.total }}")

            # Вставляем строку-тег ENDFOR после строки данных
            endfor_row = _make_tag_row(data_row, "{%tr endfor %}")
            t3.insert(list(t3).index(data_row) + 1, endfor_row)

            counts["T4_repair_works_row"] = 1

        # Удаляем все строки-заглушки (rows 2 и далее, после наших вставок)
        # Пересобираем список строк (вставки уже добавлены)
        t3_rows_new = t3.findall("w:tr", ns)
        # header=0, for_tag=1, data=2, endfor_tag=3, остальные удаляем
        for extra_row in t3_rows_new[4:]:
            t3.remove(extra_row)
        counts["T4_repair_works_removed"] = max(0, len(t3_rows_new) - 4)

    # ── Таблица запчастей/материалов (index 4) ──────────────────────────────
    t4 = tables[4]
    t4_rows = t4.findall("w:tr", ns)
    if len(t4_rows) >= 2:
        data_row = t4_rows[1]
        cells = data_row.findall("w:tc", ns)
        if len(cells) == 6:
            # Вставляем строку-тег FOR перед строкой данных
            for_row = _make_tag_row(data_row, "{%tr for item in items %}")
            t4.insert(list(t4).index(data_row), for_row)

            # Заполняем строку данных
            _set_cell_text(cells[0], "{{ item.code }}")
            _set_cell_text(cells[1], "{{ item.name }}")
            _set_cell_text(cells[2], "{{ item.unit }}")
            _set_cell_text(cells[3], "{{ item.quantity }}")
            _set_cell_text(cells[4], "{{ item.unit_price }}")
            _set_cell_text(cells[5], "{{ item.total }}")

            # Вставляем строку-тег ENDFOR после строки данных
            endfor_row = _make_tag_row(data_row, "{%tr endfor %}")
            t4.insert(list(t4).index(data_row) + 1, endfor_row)

            counts["T4_repair_parts_row"] = 1

        # Удаляем все строки-заглушки (rows 2 и далее, после наших вставок)
        t4_rows_new = t4.findall("w:tr", ns)
        for extra_row in t4_rows_new[4:]:
            t4.remove(extra_row)
        counts["T4_repair_parts_removed"] = max(0, len(t4_rows_new) - 4)

    # ── Таблица итогов (index 5): «НДС, 18%» → «НДС, {{ vat_rate }}%» ──────
    t5 = tables[5]
    for cell in t5.findall(".//w:tc", ns):
        for t_el in cell.findall(".//w:t", ns):
            if t_el.text and _VAT_18_RE.search(t_el.text):
                t_el.text = _VAT_18_RE.sub("НДС, {{ vat_rate }}%", t_el.text)
                t_el.set(f"{{{XML_NS}}}space", "preserve")
                counts["T4_vat_rate_replaced"] = counts.get("T4_vat_rate_replaced", 0) + 1
