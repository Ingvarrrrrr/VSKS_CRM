"""Единый бэкенд-источник правил по единицам измерения (ПРАВИЛО №6) —
зеркало frontend/src/utils/units.ts. Единственное место, которое решает,
упаковочная ли единица измерения — звать отсюда, не писать вторую проверку
в routers/services.

Владелец, 14.10: «когда товар меряется упаковками, должно быть количество в
упаковке» — is_pack_unit() решает, показывать ли в карточке товара поля
pack_quantity/pack_unit (см. routers/products.py, services/products_import_apply.py).
"""
from typing import Optional

# Единый список единиц измерения для подсказки в карточке товара (фронт,
# utils/units.ts::UNIT_OPTIONS) — здесь не используется напрямую (бэкенд
# принимает unit как свободную строку), оставлен как справка/источник для
# будущих серверных подсказок, чтобы не завести второй список где-то ещё.
UNIT_OPTIONS = [
    'шт.', 'упак.', 'компл.', 'пара', 'кг', 'г', 'л', 'м', 'м²', 'м³',
    'усл. ед.', 'час', 'сутки',
]

# Нормализованные (без точки, в нижнем регистре) токены упаковочных единиц —
# точное совпадение, не фаззи-подстрока (во избежание случайных совпадений
# типа «уп» внутри несвязанных слов).
PACK_UNIT_TOKENS = {
    'упак', 'уп', 'упаковка', 'пачка', 'коробка', 'кор', 'рулон', 'набор',
}


def is_pack_unit(unit: Optional[str]) -> bool:
    """Единица измерения — упаковка (товар продаётся/учитывается упаковками)?"""
    if not unit:
        return False
    normalized = unit.strip().lower().rstrip('.')
    return normalized in PACK_UNIT_TOKENS


def normalize_pack_fields(data: dict) -> None:
    """Мутирует `data` (dict с ключами ProductCreate) — если явно пришёл
    `unit` и он НЕ упаковочный, принудительно очищает pack_quantity/pack_unit
    независимо от того, что прислал клиент (защита от несогласованного
    состояния, ПРАВИЛО №6 — одно место решает, когда поля упаковки валидны).
    Если ключ `unit` не пришёл (PATCH/PUT с exclude_unset) — не трогаем."""
    if "unit" not in data:
        return
    if not is_pack_unit(data.get("unit")):
        data["pack_quantity"] = None
        data["pack_unit"] = None
