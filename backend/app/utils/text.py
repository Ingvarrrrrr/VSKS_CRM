"""Текстовые нормализаторы, общие для нескольких роутеров (Правило №6)."""
import re


def normalize_feo_name(s: str) -> str:
    """Нормализовать имя ФЭО для матчинга: срезать ведущий числовой префикс, lower+strip."""
    if not s:
        return ""
    # Срезаем «1. », «2.1 », «3) », «1.2.3. » и т.п.
    s2 = re.sub(r'^\s*\d+([.\)]\d+)*[.\)]?\s*', '', s)
    s2 = s2.lower().strip()
    # Схлопываем повторяющиеся пробелы
    s2 = re.sub(r'\s+', ' ', s2)
    return s2
