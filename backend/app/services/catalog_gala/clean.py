"""Очистка текста из выгрузок поставщиков от HTML-мусора — ЕДИНСТВЕННАЯ такая
функция для ВСЕХ конвертеров catalog_gala/ (ПРАВИЛО №6), применяется к name,
description и значениям characteristics.

Повод (владелец, 2026-10-26): во ВкусВилле названия вида
«Творог "Пластовой" обезжиренный, 250&nbsp;г» — HTML-сущности и неразрывные
пробелы долетают до карточки товара как есть.

Правила (именно в этом порядке):
  1. html.unescape — раскрывает &nbsp;, &quot;, &amp; и т.п.
  2. неразрывный пробел (\\xa0, из &nbsp; после unescape) → обычный пробел.
  3. <br>/<br/>/<br /> → "\\n" (перенос строки сохраняется осознанно — текст
     мог быть многострочным, см. состав/пищевую ценность у ВкусВилла).
  4. прочие теги (<...>) — убираются целиком, без замены.
  5. схлопывание пробелов/табов ВНУТРИ каждой строки (переносы, вставленные
     правилом 3, не трогаем) + обрезка пробелов по краям каждой строки и
     всего текста.
"""
import html
import re

_BR_RE = re.compile(r"<br\s*/?>", re.IGNORECASE)
_TAG_RE = re.compile(r"<[^>]+>")
_SPACE_RE = re.compile(r"[ \t]+")
_NBSP = "\xa0"


def clean_text(value):
    """Чистит строку по правилам выше. None/не-строка — возвращается как
    есть (вызывающему не нужно оборачивать каждый вызов проверкой типа)."""
    if not isinstance(value, str):
        return value
    text = html.unescape(value)
    text = text.replace(_NBSP, " ")
    text = _BR_RE.sub("\n", text)
    text = _TAG_RE.sub("", text)
    lines = [_SPACE_RE.sub(" ", line).strip() for line in text.split("\n")]
    text = "\n".join(lines).strip()
    return text or None
