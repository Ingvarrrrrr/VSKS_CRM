"""
rules_common.py — правила замены, применимые ко всем 8 шаблонам.

Каждое правило: (rule_id, compiled_re, replacement_str_or_callable).
re.DOTALL используется где нужно перекрыть \n внутри абзаца.
"""
import re

# XML namespace для Word document
W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"


def _make_rules():
    """
    Возвращает list[tuple[rule_id, pattern, replacement]].
    Порядок имеет значение: более специфичные правила идут раньше.
    """
    S = re.DOTALL  # внутри абзаца бывают \n (переносы строк docx)
    rules = []

    # ── 0. ПОЛНОЕ НАИМЕНОВАНИЕ ВСКС ────────────────────────────────────────
    # В преамбуле: «...организация «Всероссийский студенческий корпус спасателей» (ВСКС),
    # именуемая в дальнейшем «Заказчик»...» (услуги) или «Покупатель» (товары).
    # Ловим обе формы — роль («Заказчик»/«Покупатель») оставляем как есть после замены.
    rules.append((
        "C00a_customer_full_name_preamble_customer",
        re.compile(
            r"Всероссийская общественная молодежная организация\s+"
            r"«Всероссийский студенческий корпус спасателей»\s+"
            r"\(ВСКС\),\s*именуема\w\s+в дальнейшем «Заказчик»",
            S,
        ),
        "{{ customer_full_name }} ({{ customer_short_name }}), именуемая в дальнейшем «Заказчик»",
    ))
    rules.append((
        "C00a2_customer_full_name_preamble_buyer",
        re.compile(
            r"Всероссийская общественная молодежная организация\s+"
            r"«Всероссийский студенческий корпус спасателей»\s+"
            r"\(ВСКС\),\s*именуема\w\s+в дальнейшем «Покупатель»",
            S,
        ),
        "{{ customer_full_name }} ({{ customer_short_name }}), именуемая в дальнейшем «Покупатель»",
    ))

    # repair_vehicle: ВСКС стоит второй стороной (начинается с «и Всероссийская...»)
    # Захватываем и «действующего на основании Устава» — C06 потом ничего не найдёт.
    rules.append((
        "C00b_customer_full_name_repair_vehicle",
        re.compile(
            r"и\s+Всероссийская общественная молодежная организация\s+"
            r"«Всероссийский студенческий корпус спасателей»\s+"
            r"\(ВСКС\),\s*в лице президента Козеева Евгения Викторовича,\s*"
            r"действующего на основании Устава",
            S,
        ),
        "и {{ customer_full_name }} ({{ customer_short_name }}), "
        "в лице {{ customer_signatory_position }} {{ customer_signatory_name }}, "
        "действующего на основании {{ customer_signatory_basis }}",
    ))

    # repair_framework: «___ региональное отделение ВСЕРОССИЙСКОЙ... (__РО ВСКС)»
    # В преамбуле и в реквизитах — региональное отделение
    rules.append((
        "C00c_customer_full_name_region_preamble",
        re.compile(
            r"_+\s+региональное отделение Всероссийской общественной молодежной организации\s+"
            r"«Всероссийский студенческий корпус спасателей»\s+"
            r"\(__РО ВСКС\)",
            S,
        ),
        "{{ customer_full_name }} ({{ customer_short_name }})",
    ))

    # repair_framework реквизиты: «Наименование: ___ региональное отделение ...»
    rules.append((
        "C00d_customer_full_name_region_requisites",
        re.compile(
            r"Наименование:\s+_+\s+региональное отделение Всероссийской общественной молодежной организации\s+"
            r"«Всероссийский студенческий корпус спасателей»",
            S,
        ),
        "Наименование: {{ customer_full_name }}",
    ))

    # services_large — определение в тексте: «Заказчик, ВСКС – Всероссийская ...»
    rules.append((
        "C00e_customer_full_name_definition",
        re.compile(
            r"Заказчик,\s+ВСКС\s+–\s+Всероссийская общественная молодежная организация\s+"
            r"«Всероссийский студенческий корпус спасателей»\.",
            S,
        ),
        "Заказчик, {{ customer_short_name }} – {{ customer_full_name }}.",
    ))

    # ГПХ — согласие на ПД: «...организации «ВСКС» (ВСКС), зарегистрированному по адресу...»
    # Уже покрыто C23b, но полное имя перед ним
    rules.append((
        "C00f_customer_full_name_pd_consent",
        re.compile(
            r"Всероссийской общественной молодежной организации\s+"
            r"«Всероссийский студенческий корпус спасателей»\s+"
            r"\(ВСКС\),\s*зарегистрированному по адресу:",
            S,
        ),
        "{{ customer_full_name }} ({{ customer_short_name }}), зарегистрированному по адресу:",
    ))

    # ── 1. ШАПКА: «Договор № _____» → номер договора ──────────────────────
    rules.append((
        "C01_contract_number",
        re.compile(r"Договор №\s*_+", S),
        "Договор № {{ contract_number }}",
    ))

    # «Договор поставки № _____ от «___» ______ 20__ г.» (в шапке приложений goods)
    rules.append((
        "C01b_goods_app_header",
        re.compile(r"к Договору поставки №\s*_+\s*от\s*«___» _+\s*20__\s*г\.", S),
        "к Договору поставки № {{ contract_number }} "
        "от «{{ contract_date_day }}» {{ contract_date_month }} {{ contract_date_year }} г.",
    ))

    # ГПХ: «ДОГОВОР № ________» — заголовок всего документа (весь абзац)
    rules.append((
        "C01d_gph_title_number",
        re.compile(r"^ДОГОВОР №\s*_+$", S),
        "ДОГОВОР № {{ contract_number }}",
    ))

    # ГПХ: «к Договору № ____________ от «___» ________ 202__ г.»
    rules.append((
        "C01c_gph_app_header",
        re.compile(r"к Договору №\s*_+\s*от\s*«___» _+\s*202?_+\s*г\.", S),
        "к Договору № {{ contract_number }} "
        "от «{{ contract_date_day }}» {{ contract_date_month }} {{ contract_date_year }} г.",
    ))

    # ГПХ: ««_____» _______ 202___ г.» — дата в шапке (в ячейке таблицы)
    # Паттерн: «_____»\xa0_______\xa0202___\xa0г. (с неразрывными пробелами)
    rules.append((
        "C02c_gph_header_date",
        re.compile(
            r"«_+»[\s\xa0]+_+[\s\xa0]+202_+[\s\xa0]+г\.",
            S,
        ),
        "«{{ contract_date_day }}» {{ contract_date_month }} {{ contract_date_year }} г.",
    ))

    # «г. Москва  «___» _______ 20__ г.» (services/goods)
    rules.append((
        "C02_contract_city_date",
        re.compile(
            r"г\.\s*(Москва)\s+"
            r"«___»\s+_+\s+20__\s+г\.",
            S,
        ),
        "{{ contract_city }}\t\t\t\t\t\t\t«{{ contract_date_day }}» {{ contract_date_month }} {{ contract_date_year }} г.",
    ))

    # repair/framework: «г. Москва ... «___» ________ 2025 года» (год вписан)
    rules.append((
        "C02b_contract_city_date_year",
        re.compile(
            r"г\.\s*(Москва)\s+"
            r"«___»\s+_+\s+\d{4}\s+года",
            S,
        ),
        "{{ contract_city }}\t\t\t\t\t\t\t«{{ contract_date_day }}» {{ contract_date_month }} {{ contract_date_year }} г.",
    ))

    # В приложениях: «от «____» _______ 20__ г. № _______»
    rules.append((
        "C03_app_header_date",
        re.compile(
            r"от «____» _+\s+20__\s+г\.\s+№\s+_+",
            S,
        ),
        "от «{{ contract_date_day }}» {{ contract_date_month }} {{ contract_date_year }} г. № {{ contract_number }}",
    ))

    # Шапки методики: «г. Москва, 20___»
    rules.append((
        "C04_year_in_header",
        re.compile(r"\bг\.\s*Москва,\s*20_+\b", S),
        "{{ contract_city }}, {{ contract_date_year }}",
    ))

    # ── 2. ПРЕАМБУЛА ЗАКАЗЧИКА ─────────────────────────────────────────────
    # services/goods/gph: «...в лице президента Козеева Евгения Викторовича, действующего на основании Устава, с одной стороны, и»
    rules.append((
        "C05_customer_preamble_vsks",
        re.compile(
            r"в лице президента Козеева Евгения Викторовича,\s*"
            r"действующего на основании Устава,\s*с одной стороны,\s*и",
            S,
        ),
        "в лице {{ customer_signatory_position }} {{ customer_signatory_name }}, "
        "действующего на основании {{ customer_signatory_basis }}, с одной стороны, и",
    ))

    # repair_vehicle: «...ВСКС, в лице президента Козеева...» (без «с одной стороны»)
    rules.append((
        "C06_customer_preamble_vsks_v2",
        re.compile(
            r"в лице президента Козеева Евгения Викторовича,\s*"
            r"действующего на основании Устава",
            S,
        ),
        "в лице {{ customer_signatory_position }} {{ customer_signatory_name }}, "
        "действующего на основании {{ customer_signatory_basis }}",
    ))

    # framework: «в лице Председателя Совета ____________, действующего на основании Устава»
    rules.append((
        "C07_customer_preamble_region",
        re.compile(
            r"в лице Председателя Совета\s+_+,?\s*"
            r"действующего на основании Устава",
            S,
        ),
        "в лице {{ customer_signatory_position }} {{ customer_signatory_name }}, "
        "действующего на основании {{ customer_signatory_basis }}",
    ))

    # ── 3. ПРЕАМБУЛА ИСПОЛНИТЕЛЯ (ЮЛ) ─────────────────────────────────────
    rules.append((
        "C08_contractor_preamble_ul",
        re.compile(
            r"_+\s*\(_+\),\s*именуемое/ая в дальнейшем «Исполнитель»,\s*"
            r"в лице _+,?\s*действующего на основании _+,?\s*",
            S,
        ),
        "{{ contractor_full_name }} ({{ contractor_short_name }}), "
        "именуемое/ая в дальнейшем «Исполнитель», "
        "в лице {{ contractor_signatory_position }} {{ contractor_signatory_name }}, "
        "действующего на основании {{ contractor_signatory_basis }}, ",
    ))

    # goods: «_________________________ (______________), именуем__ в дальнейшем «Поставщик»...»
    rules.append((
        "C08b_contractor_preamble_ul_goods",
        re.compile(
            r"_+\s*\(_+\),\s*именуем\w{0,2}\s+в дальнейшем «Поставщик»,\s*"
            r"в лице _+,?\s*действующего на основании _+,?\s*",
            S,
        ),
        "{{ contractor_full_name }} ({{ contractor_short_name }}), "
        "именуемое/ая в дальнейшем «Поставщик», "
        "в лице {{ contractor_signatory_position }} {{ contractor_signatory_name }}, "
        "действующего на основании {{ contractor_signatory_basis }}, ",
    ))

    # ── 3б. ПРЕАМБУЛА ИСПОЛНИТЕЛЯ (физлицо — ГПХ) ─────────────────────────
    # «гражданин Российской Федерации ___________________, далее именуемый «Исполнитель»»
    rules.append((
        "C08c_contractor_preamble_fl",
        re.compile(
            r"гражданин Российской Федерации\s+_+,\s*далее именуемый «Исполнитель»",
            S,
        ),
        "гражданин Российской Федерации {{ contractor_full_name }}, далее именуемый «Исполнитель»",
    ))

    # ── 4. ПРЕАМБУЛА ИСПОЛНИТЕЛЯ (ИП) — услуги/ГПХ ────────────────────────
    # «Индивидуальный предприниматель __________________ (ИП __________), именуемый ... (ОГРНИП ___)»
    rules.append((
        "C09_contractor_preamble_ip",
        re.compile(
            r"Индивидуальный предприниматель\s+_+\s*\(ИП\s+_+\),\s*"
            r"именуемый в дальнейшем «Исполнитель»,\s*в своем лице и действующий в своих собственных интересах,\s*"
            r"зарегистрированный в качестве индивидуального предпринимателя в соответствии\s+"
            r"[\s\S]{0,10}?законодательством"
            r"[\s\S]{0,60}?"
            r"Российской Федерации \(ОГРНИП _+\),",
            S,
        ),
        "Индивидуальный предприниматель {{ contractor_full_name }} "
        "(ИП {{ contractor_short_name }}), именуемый в дальнейшем «Исполнитель», "
        "в своем лице и действующий в своих собственных интересах, "
        "зарегистрированный в качестве индивидуального предпринимателя в соответствии с "
        "законодательством Российской Федерации (ОГРНИП {{ contractor_ogrnip }}),",
    ))

    # goods: ИП именуется «Поставщик»
    rules.append((
        "C09b_contractor_preamble_ip_goods",
        re.compile(
            r"Индивидуальный предприниматель\s+_+\s*\(ИП\s+_+\),\s*"
            r"именуемый[\s\S]{0,30}?«Поставщик»,\s*в своем лице и действующий в своих собственных интересах,\s*"
            r"зарегистрированный в качестве индивидуального предпринимателя в соответствии\s+"
            r"[\s\S]{0,10}?законодательством"
            r"[\s\S]{0,60}?"
            r"Российской Федерации \(ОГРНИП _+\),\s*",
            S,
        ),
        "Индивидуальный предприниматель {{ contractor_full_name }} "
        "(ИП {{ contractor_short_name }}), именуемый в дальнейшем «Поставщик», "
        "в своем лице и действующий в своих собственных интересах, "
        "зарегистрированный в качестве индивидуального предпринимателя в соответствии с "
        "законодательством Российской Федерации (ОГРНИП {{ contractor_ogrnip }}), ",
    ))

    # repair_vehicle: ИП стоит ПЕРВЫМ, содержит «ОГРНИП ___ от ___ г.), именуемый в дальнейшем «Исполнитель»»
    rules.append((
        "C10_contractor_preamble_ip_repair",
        re.compile(
            r"Индивидуальный предприниматель\s+_+\s*\(ИП\s+_+\),\s*"
            r"в своем лице и действующий в своих собственных интересах,\s*"
            r"зарегистрированный в качестве индивидуального предпринимателя в соответствии\s+"
            r"[\s\S]{0,10}?законодательством"
            r"[\s\S]{0,80}?"
            r"Российской Федерации \(ОГРНИП _+(?:\s+от\s+_+г\.)?\),\s*"
            r"(?:именуемый в дальнейшем «Исполнитель»,\s*)?",
            S,
        ),
        "Индивидуальный предприниматель {{ contractor_full_name }} "
        "(ИП {{ contractor_short_name }}), "
        "в своем лице и действующий в своих собственных интересах, "
        "зарегистрированный в качестве индивидуального предпринимателя в соответствии с "
        "законодательством Российской Федерации (ОГРНИП {{ contractor_ogrnip }}), "
        "именуемый в дальнейшем «Исполнитель», ",
    ))

    # ── 5. R7 — СОГЛАШЕНИЕ О СУБСИДИИ ─────────────────────────────────────
    # п.1.3: «заключенного с Министерством труда ... № 149-10-... от ...»
    # Текст может содержать \n
    rules.append((
        "C11_subsidy_agreement_p13",
        re.compile(
            r"заключенного с Министерств\w+[\s\S]{1,80}?Российской Федерации\s*"
            r"(?:\([^)]+\)\s*)?"
            r"№\s+\S+\s+от\s+\S+\s+г\.",
            S,
        ),
        "заключенного с {{ subsidy_ministry_name }} "
        "№ {{ subsidy_agreement_number }} от {{ subsidy_agreement_date }} г.",
    ))

    # п.4.5: «заключенного между ВСКС и Министерством ... № ... от ...»
    rules.append((
        "C12_subsidy_agreement_p45",
        re.compile(
            r"заключенного между ВСКС и Министерств\w+[\s\S]{1,80}?Российской Федерации\s*"
            r"(?:\([^)]+\)\s*)?"
            r"№\s+\S+\s+от\s+\S+\s+г\.",
            S,
        ),
        "заключенного между ВСКС и {{ subsidy_ministry_name }} "
        "№ {{ subsidy_agreement_number }} от {{ subsidy_agreement_date }} г.",
    ))

    # п.4.5: «предоставившим субсидию (Министерство труда ... Российской Федерации),»
    rules.append((
        "C13_subsidy_grantor_p45",
        re.compile(
            r"предоставившим субсидию \(Министерств\w+[\s\S]{1,80}?Российской Федерации\),",
            S,
        ),
        "предоставившим субсидию ({{ subsidy_ministry_name }}),",
    ))

    # п.4.6: «В случае уменьшения Министерству труда ... как получателю»
    rules.append((
        "C14_subsidy_ministry_p46",
        re.compile(
            r"В случае уменьшения Министерств\w+[\s\S]{1,80}?Российской Федерации\s+как получателю",
            S,
        ),
        "В случае уменьшения {{ subsidy_ministry_name }} как получателю",
    ))

    # Методика: «Соглашения заключенного с Министерством труда ... Российской Федерации.»
    rules.append((
        "C15_subsidy_agreement_methodika",
        re.compile(
            r"Соглашения заключенного с Министерств\w+[\s\S]{1,80}?Российской Федерации\.",
            S,
        ),
        "Соглашения заключенного с {{ subsidy_ministry_name }}.",
    ))

    # R7 ФАДМ — gph/repair_vehicle: «заключенного между ВСКС и Федеральным агентством
    # по делам молодежи (Росмолодежь) № 091-10-2025-032 от 24.02.2025 г.»
    # Должно сработать ДО общих паттернов C11/C12 (которые ловят «Министерство»).
    rules.append((
        "C16_subsidy_agreement_fadm",
        re.compile(
            r"заключенного между ВСКС и Федеральным агентством\s+"
            r"по делам молодежи\s*\(Росмолодежь\)\s*"
            r"№\s+\S+\s+от\s+\S+\s+г\.",
            S,
        ),
        "заключенного между ВСКС и {{ subsidy_grantor_name }} "
        "№ {{ subsidy_agreement_number }} от {{ subsidy_agreement_date }} г.",
    ))

    # R7 ФАДМ — «предоставившим субсидию (Федеральным агентством по делам молодежи)»
    rules.append((
        "C17_subsidy_grantor_fadm",
        re.compile(
            r"предоставившим субсидию \(Федеральным агентством по делам молодежи\),",
            S,
        ),
        "предоставившим субсидию ({{ subsidy_grantor_name }}),",
    ))

    # R7 repair_framework — региональный бюджет:
    # «Соглашения №___ о предоставлении субсидии из бюджета _______ в 2025 году от _______ 2025 года,
    #  заключенного между _____________ РЕГИОНАЛЬНЫМ ОТДЕЛЕНИЕМ ... и МИНИСТЕРСТВОМ ...»
    rules.append((
        "C18_subsidy_agreement_framework",
        re.compile(
            r"Соглашения №_+\s+о предоставлении субсидии из бюджета\s+_+\s+"
            r"в \d{4} году от\s+_+\s+\d{4} года,\s+"
            r"заключенного между\s+_+\s+РЕГИОНАЛЬНЫМ ОТДЕЛЕНИЕМ"
            r"[\s\S]{1,200}?"
            r"и МИНИСТЕРСТВОМ\s+\S+[\s\S]{0,80}?\.",
            S,
        ),
        "Соглашения № {{ subsidy_agreement_number }} о предоставлении субсидии "
        "из бюджета {{ subsidy_grantor_name }} в {{ contract_date_year }} году "
        "от {{ subsidy_agreement_date }}, "
        "заключенного между {{ customer_full_name }} и {{ subsidy_ministry_name }}.",
    ))

    # ── 6. РЕКВИЗИТЫ ЗАКАЗЧИКА — раздел «Адреса и реквизиты» ─────────────
    rules.append((
        "C20_customer_inn_kpp",
        re.compile(r"ИНН/КПП\s+7731178803/772901001", S),
        "ИНН/КПП {{ customer_inn }}/{{ customer_kpp }}",
    ))
