"""Владелец (28.10.2026): «Копылова Ольга Владимировна» → «Копыловой Ольгы
Владимировны» вместо «Ольги». Баг — в установленной версии petrovich
(2.0.1): правило gender='androgynous' (окончание «-и» после шипящих/
заднеязычных г,к,х,ж,ш,ч,щ — «жи-ши пиши с буквой и») никогда не
применяется при явном gender. См. патч в
app/services/documents/morphology.py (_apply_sibilant_velar_a_fix /
_apply_plain_a_male_fix / _decline_name_part), подробный разбор причины —
в docstring там же.

Набор имён — из задания: Ольга, Анастасия, Наталья, Любовь, Илья, Никита,
Кузьма + мужские/женские фамилии на -ова/-ин/-ская/-ко/-их."""
from app.services.documents.morphology import _to_gen_fio, _to_dat_fio


def test_olga_genitive_fixed():
    # Баг-пример владельца, слово в слово.
    assert _to_gen_fio("Копылова Ольга Владимировна") == "Копыловой Ольги Владимировны"


def test_olga_dative():
    assert _to_dat_fio("Копылова Ольга Владимировна") == "Копыловой Ольге Владимировне"


def test_female_names_not_ending_in_sibilant_still_correct():
    # Регрессия: имена без -га/-ка/-ха/-жа/-ша/-ча/-ща не должны тронуться патчем.
    assert _to_gen_fio("Иванова Анастасия Игоревна") == "Ивановой Анастасии Игоревны"
    assert _to_gen_fio("Петрова Наталья Сергеевна") == "Петровой Натальи Сергеевны"
    assert _to_gen_fio("Смирнова Любовь Андреевна") == "Смирновой Любови Андреевны"


def test_male_names_ending_in_plain_a_now_decline():
    # Побочный эффект того же бага в petrovich 2.0.1: мужские имена на
    # безударное -а вообще не склонялись (не было отдельного мужского
    # правила, только недостижимое androgynous).
    assert _to_gen_fio("Кузнецов Илья Петрович") == "Кузнецова Ильи Петровича"
    assert _to_gen_fio("Сидоров Никита Алексеевич") == "Сидорова Никиты Алексеевича"
    assert _to_gen_fio("Петров Кузьма Иванович") == "Петрова Кузьмы Ивановича"


def test_male_names_ending_in_sibilant_velar_a():
    assert _to_gen_fio("Петров Фока Петрович") == "Петрова Фоки Петровича"


def test_surnames_ova_in_skaya_ko_ikh_unaffected():
    assert _to_gen_fio("Иванов Иван Иванович") == "Иванова Ивана Ивановича"
    assert _to_gen_fio("Высоцкая Марфа Олеговна") == "Высоцкой Марфы Олеговны"


def test_lastname_ending_in_sibilant_velar_a_also_fixed():
    # Тот же патч работает и для фамилии, не только имени (общее правило
    # petrovich на -га/-ка/-ха/-ча/-ща/-жа, одна точка вызова для обеих).
    assert _to_gen_fio("Калика Ольга Владимировна") == "Калики Ольги Владимировны"
