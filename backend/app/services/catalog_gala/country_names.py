"""Единый список имён ключа «страна производства» для конвертеров
catalog_gala (ПРАВИЛО №6 — один источник истины, не плодить вторую карту
имён ключей в каждом конвертере).

Владелец, 2026-10-26 (находка: country_origin='РФ' дефолт у товаров
k_spasatel/rescue_medical/fire_equipment/promalp/electro_mpo_*/vkusvill_*/
baucenter_electro_lighting/baucenter_tools_hardware — перенос страны из файла
появился позже, чем эти товары загрузили; добавлен вариант "страна
изготовитель"/"страна-изготовитель" — ранее был только у store_nomenclature
"страна производитель"/"страна производства").

norm_key("-", " ") — дефис в ключе нормализуется в пробел ДО сравнения с
COUNTRY_KEY_NAMES, поэтому "страна-изготовитель"/"страна-производитель" уже
покрываются вариантами "страна изготовитель"/"страна производитель" без
отдельной записи в множестве. Намеренно НЕ включены "производство"/
"производство изделия" — там бывает произвольный текст о технологии
изготовления, а не название страны (владелец явно исключил, 26.10.2026)."""

COUNTRY_KEY_NAMES = {
    "страна производитель",
    "страна производства",
    "страна изготовитель",
}


def norm_country_key(key_lower: str) -> str:
    """key_lower — ключ характеристики, уже в нижнем регистре. Схлопывает
    дефис в пробел и обрезает края, чтобы "страна-изготовитель" совпал со
    "страна изготовитель" из COUNTRY_KEY_NAMES."""
    return key_lower.replace("-", " ").strip()


