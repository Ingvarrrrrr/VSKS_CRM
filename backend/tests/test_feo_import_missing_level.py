"""Тесты на `detect_missing_level_hints` (backend/app/services/feo_import_missing_level.py)
— решение владельца 10.10.2026: импорт ФЭО предупреждает, когда похоже, что
в файле забыт «Уровень 4»/«Уровень 3» подкатегории, но НИЧЕГО не меняет —
дерево строится по файлу буквально, предупреждение только текстом.

Чистая функция без БД — колонки задаются как индексы в собственном списке
`row`, своего макета строки не заводим: индексы читаются по порядку, как в
feo_import_apply.py (c_lvl2/c_lvl3/c_lvl4/c_lvl5/c_row_plan_sum)."""
from app.services.feo_import_missing_level import detect_missing_level_hints

# Индексы колонок тестовой строки: [lvl2, lvl3, lvl4, lvl5(Плановая позиция), plan_sum]
C_LVL2, C_LVL3, C_LVL4, C_LVL5, C_PLAN = 0, 1, 2, 3, 4


def row(lvl2=None, lvl3=None, lvl4=None, lvl5=None, plan=None):
    return [lvl2, lvl3, lvl4, lvl5, plan]


def _detect(rows):
    return detect_missing_level_hints(
        rows, C_LVL2, C_LVL3, C_LVL4, C_LVL5,
        C_PLAN, None, None, None,
    )


def test_boevoy_example_250_254_warns_with_rows_and_subcat_name():
    """Боевой пример владельца: стр.250–254 листа «ДНРР». Итог строки 251
    (10954.41) = сумма строк 252–254 (2762.92+1904.45+6287.04); у строк 253 и
    254 «Уровень 4» не указан, у 252 указан («Бытовая техника») — ровно одна
    названная подкатегория среди набранных строк называется в тексте."""
    rows = []
    # Доводим нумерацию строк файла до 250 искусственными пустыми строками,
    # чтобы в предупреждении фигурировали те же номера, что в задаче (не
    # обязательно для корректности функции, но облегчает проверку текста).
    # row_num = index + 2 (enumerate(rows, start=2)) — 248 пустых строк дают
    # следующей append-строке row_num=250.
    while len(rows) < 248:
        rows.append(row())
    rows.append(row(lvl3="Расходы на приобретение основных средств (…)", lvl4="Мебель", lvl5="Столы для спикеров", plan="8000"))  # 250
    rows.append(row(lvl3="Расходы на приобретение основных средств (…)", lvl4=None, lvl5=None, plan="10954.41"))  # 251 — итог
    rows.append(row(lvl3="Расходы на приобретение основных средств (…)", lvl4="Бытовая техника", lvl5="Чайник электрический", plan="2762.92"))  # 252
    rows.append(row(lvl3="Расходы на приобретение основных средств (…)", lvl4=None, lvl5="Чайник электрический", plan="1904.45"))  # 253
    rows.append(row(lvl3="Расходы на приобретение основных средств (…)", lvl4=None, lvl5="Термопот", plan="6287.04"))  # 254

    warns = _detect(rows)
    assert len(warns) == 1
    w = warns[0]
    assert w["kind"] == "missing_level_hint"
    assert w["row"] == 251
    assert "251" in w["message"] and "253" in w["message"] and "254" in w["message"]
    assert "Бытовая техника" in w["message"]
    assert "Уровень 4" in w["message"]
    # «равен сумме строк 252–254» — диапазон всех набранных позиций (252 с
    # уровнем, 253/254 без); «но у строк 253–254 подкатегория не указана» —
    # только проблемные строки (252 там не называется, у неё уровень указан).
    assert "сумме строк 252–254" in w["message"]
    assert "у строк 253–254 подкатегория не указана" in w["message"]


def test_sum_mismatch_no_warning():
    """Сумма строки-итога НЕ совпадает с суммой последующих позиций —
    не наш случай, предупреждения нет."""
    rows = [
        row(lvl3="Категория", lvl4="Подкат", lvl5="Поз. с уровнем", plan="100"),
        row(lvl3="Категория", lvl4=None, lvl5=None, plan="500"),  # итог, но...
        row(lvl3="Категория", lvl4=None, lvl5="Позиция A", plan="200"),
        row(lvl3="Категория", lvl4=None, lvl5="Позиция B", plan="250"),  # 200+250=450 != 500
    ]
    assert _detect(rows) == []


def test_category_without_subcategories_no_warning():
    """У категории в файле вообще нет подкатегорий (никогда не заполнен
    следующий уровень) — итог + позиции без уровня — это не аномалия,
    а обычный плоский список позиций категории."""
    rows = [
        row(lvl3="Категория без подуровней", lvl4=None, lvl5=None, plan="300"),  # итог
        row(lvl3="Категория без подуровней", lvl4=None, lvl5="Позиция A", plan="100"),
        row(lvl3="Категория без подуровней", lvl4=None, lvl5="Позиция B", plan="200"),
    ]
    assert _detect(rows) == []


def test_itog_with_level_named_no_warning():
    """Итог, у которого САМ «Уровень 4» заполнен — это уже не «итог
    категории без названия подкатегории», а обычная подкатегория со своим
    планом; правило не касается этого случая (нет «следующего уровня» глубже
    Уровня 4)."""
    rows = [
        row(lvl3="Категория", lvl4="Другая подкат", lvl5=None, plan="300"),  # итог, но Уровень 4 указан
        row(lvl3="Категория", lvl4="Подкат", lvl5="Позиция A", plan="100"),
        row(lvl3="Категория", lvl4="Подкат", lvl5="Позиция B", plan="200"),
    ]
    assert _detect(rows) == []


def test_no_plan_sum_no_warning():
    """Строка без «Плановой позиции» и без суммы плана (0/пусто) — нет
    сигнала для сравнения, предупреждения нет."""
    rows = [
        row(lvl3="Категория", lvl4="Подкат", lvl5="Позиция", plan="100"),
        row(lvl3="Категория", lvl4=None, lvl5=None, plan=None),
        row(lvl3="Категория", lvl4=None, lvl5="Позиция B", plan="100"),
    ]
    assert _detect(rows) == []
