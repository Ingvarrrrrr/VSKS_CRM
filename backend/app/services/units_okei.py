def is_okei_unit(name: str | None) -> bool:
    """True, если name — РОВНО одно из названий списка (без приведения)."""
    return bool(name) and name in OKEI_NAME_SET


def normalize_unit(raw: str | None) -> str | None:
    """Свободное/старое написание единицы → каноничное название из списка
    выше, либо None, если не распознано (неизвестное НЕ выдумываем — вызывающий
    код решает, оставить как есть или потребовать выбора из списка)."""
    if not raw:
        return None
    return _NORM_TO_CANONICAL.get(_norm(raw))


def okei_code_for(canonical_name: str | None) -> str | None:
    """Каноничное название → код ОКЕИ. Для произвольной строки сначала
    normalize_unit(), потом сюда."""
    if not canonical_name:
        return None
    return _OKEI_BY_NAME.get(canonical_name)


def okei_for_unit(unit_name: str | None) -> tuple[str | None, str | None]:
    """Удобный разовый вызов: свободное название → (каноничное название, код
    ОКЕИ), либо (None, None) если не распознано ни точным совпадением, ни
    через приведение старых написаний."""
    canonical = unit_name if is_okei_unit(unit_name) else normalize_unit(unit_name)
    if not canonical:
        return None, None
    return canonical, okei_code_for(canonical)
