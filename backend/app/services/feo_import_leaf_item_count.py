"""Импорт ФЭО: сколько строк файла на каждом точном пути Уровень2/3/4 сами
себя называют и подразделом, и позицией одновременно («Плановая позиция» =
имя самого глубокого заполненного уровня ЭТОЙ строки) — единственный
пред-проход, решающий «это строка-итог категории или обычная позиция»,
когда сработало self-declared (см. `item_name_equals_category` в
feo_import_apply.py).

Боевой инцидент 12.10.2026, субсидия «ДНР 3», файл «ХО_ЛНР_ДНР_МАКЛЮК_
Отправил.xlsx», лист «ДНРР»:
  стр.150  L3=«Расходы закупка товаров…» L4=«Проезд, проживание, питание»  ПП ПУСТО                            700 000,00  (итог, не self-declared)
  стр.151  тот же путь                                                     ПП=«Проезд, проживание, питание» (=L4)  407 184,10  (self-declared)
  стр.152  тот же путь                                                     ПП=«Проезд, проживание, питание» (=L4)  292 815,90  (self-declared)
Старое правило («имя позиции = имя категории ⇒ это строка-итог, не
позиция») считало И строку 151, И строку 152 итогом ОДНОЙ и той же
категории — вторая запись затирала первую в `collected_plan` (Правило №6,
один показатель — одно место: тут было два источника суммы категории, а
не один), и 407 184,10 терялись молча.

Слова владельца (09.10.2026, дословно): «одинаковое название не даёт
оснований смешивать категорию и плановую… плановая так и остаётся на
плановой и не является категорией и не мержится с категорией, даже если
они имеют одинаковое название». Решает не единичное совпадение имени, а
факт: сколько строк на этом ТОЧНО ТАКОМ ЖЕ пути САМИ СЕБЯ так назвали. Если
больше одной — ни одна из них не может быть «итогом» (итог — это ОДНО
число, две self-declared строки с РАЗНЫМИ суммами на одном месте явно не
итог, а две разные позиции с совпавшим именем). Если self-declared строка
на своём пути ОДНА — старое поведение (строка-итог, budget категории +
обобщённая позиция через `collected_plan`/`apply_collected_plan`, боевой
случай «Катер») не меняется — обычная ветка feo_import_apply.py решит,
совпадает ли её сумма с суммой соседних строк (`group_total_row`).

Важно: считаются только ДЕЙСТВИТЕЛЬНО self-declared строки (имя позиции =
имя своего самого глубокого уровня), а НЕ любая строка с заполненной
«Плановой позицией» на этом пути — иначе категория с одной self-declared
строкой и ОДНОЙ обычной (другим именем) позицией внутри неё (боевой случай
«Аренда Хендей ГрандСтарекс» под «Аренда автотранспортных средств», см.
test_feo_import_node_by_level_name.py::
test_item_name_not_matching_anywhere_gets_no_warning) ошибочно получила бы
count=2 и потеряла бы budget подраздела, хотя там всего ОДНА self-declared
строка и спора вокруг «что здесь итог» нет.

Единственное место этого счёта (Правило №6) — вызывается один раз из
`feo_import_apply.py` (`apply_rows`), использует только существующие
хелперы `feo_import_common.py` (get_cell/norm), собственного разбора ячеек
не заводит.
"""
from app.services.feo_import_common import get_cell, norm


def count_self_declared_rows_by_path(rows, c_lvl2, c_lvl3, c_lvl4, c_lvl5) -> dict:
    """Количество self-declared строк (не служебных, без «←» — «Плановая
    позиция» ЭТОЙ строки совпадает после нормализации с её же самым глубоким
    заполненным уровнем) на каждом точном пути (нормализованные Уровень2/3/4
    этой строки, как есть в файле — без продвижения/дедупа, которые
    происходят позже в основном цикле). Ключ — кортеж трёх строк (пустая
    строка, если колонка уровня не задействована в маппинге этого импорта
    или ячейка пуста)."""
    counts: dict[tuple[str, str, str], int] = {}
    if c_lvl5 is None:
        return counts
    for row in rows:
        l5 = get_cell(row, c_lvl5)
        if not l5 or l5.startswith("←"):
            continue
        l2 = get_cell(row, c_lvl2) if c_lvl2 is not None else None
        l3 = get_cell(row, c_lvl3) if c_lvl3 is not None else None
        l4 = get_cell(row, c_lvl4) if c_lvl4 is not None else None
        _deepest = next(
            (v for v in (l4, l3, l2) if v and not v.startswith("←")),
            None,
        )
        if _deepest is None or norm(_deepest) != norm(l5):
            continue
        key = (norm(l2 or ""), norm(l3 or ""), norm(l4 or ""))
        counts[key] = counts.get(key, 0) + 1
    return counts
