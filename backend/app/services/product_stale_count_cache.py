"""Кэш счётчика «требует актуализации» по каталогу товаров (ПРАВИЛО №6:
источник самого числа — ОДИН, services/product_search.py::count_stale_products
+ price_freshness_sql.py::stale_condition; этот модуль только придерживает
результат в памяти процесса, чтобы не пересчитывать на КАЖДЫЙ запрос).

Повод (владелец, 26.10.2026, замер на 263 тыс. товаров): GET /api/products/page
раньше считал stale_total БЕЗУСЛОВНО на каждый вызов (даже когда ответ не
менялся за секунды между нажатиями клавиш при поиске) — это самостоятельный
full-scan по price_updated_at (нет и не может быть простого B-tree индекса:
порог «сколько дней считать просрочкой» зависит от category/product_type/
item_kind/fx-триггера, то есть от ЗНАЧЕНИЯ строки, не от константы), замер
~200-240мс на 263 тыс. строк. Бейдж на странице «Товары» не требует точности
до последней секунды — TTL-кэш 60с по ключу org_id достаточен (владелец сам
допустил такой вариант в задании при условии, что сырой расчёт <500мс; здесь
~240мс — укладывается).

Инвалидация по записи цены СОЗНАТЕЛЬНО не сделана: цену товара пишут из
нескольких мест (ручная актуализация, массовое редактирование, импорт,
предложения правок) — раскладывать invalidate_stale_count_cache() по всем им
означало бы второй механизм синхронизации вместо одного TTL (тоже Правило №6,
но в обратную сторону: не плодить точки, которые обязаны не забыть вызвать
сброс). Худший случай — бейдж отстаёт на ≤60 секунд от реальной актуализации,
это приемлемо для некритичного счётчика-подсказки.
"""
import time
from typing import Optional

TTL_SECONDS = 60.0

_cache: dict[Optional[int], tuple[float, int]] = {}


async def get_stale_count_cached(org_id: Optional[int], compute) -> int:
    """compute — асинхронная функция без аргументов, считающая актуальное
    значение (вызывающая сторона передаёт замыкание над db/freshness_ctx,
    этот модуль ничего не знает о БД)."""
    now = time.monotonic()
    cached = _cache.get(org_id)
    if cached is not None and (now - cached[0]) < TTL_SECONDS:
        return cached[1]
    value = await compute()
    _cache[org_id] = (now, value)
    return value


def clear_stale_count_cache() -> None:
    """Только для тестов — сбрасывает кэш между прогонами."""
    _cache.clear()
