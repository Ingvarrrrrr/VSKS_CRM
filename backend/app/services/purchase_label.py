"""Единый хелпер человекочитаемого номера закупки для текстов — отказов (409),
уведомлений (email/Telegram/чат), подписей в списках согласования и аудит-трейла.

ПРАВИЛО №6 (владелец, 2026-09-30): формат "№{p.purchase_number or p.id}" был
продублирован по всему backend. purchase_number — легаси-поле, почти всегда
NULL (см. app/services/wish_access.py::_wish_locked_descr, докстринг до этой
правки), поэтому текст показывал либо голый внутренний id, либо случайный
числовой purchase_number, которого нет в реестре закупок — ни то, ни другое
не помогает найти закупку в UI. Ровно эта путаница дошла до владельца
2026-09-30: заявка №68 → отказ ссылался на «закупку 631» (purchase_number),
хотя реальный, видимый в реестре номер — РЕЕ-2026-00941 (registry_number).

Приоритет: registry_number (актуальный реестровый номер) → purchase_number
(легаси, почти всегда пуст) → id (последний фолбэк, чтобы текст не остался
без номера вовсе).
"""


def purchase_label(p) -> str:
    """«№{registry_number|purchase_number|id}» — без слова «закупка»,
    вызывающий сам решает контекст («закупка №...», «закупкой №...», просто
    «№...» в перечислении)."""
    num = (
        getattr(p, "registry_number", None)
        or getattr(p, "purchase_number", None)
        or getattr(p, "id", None)
    )
    return f"№{num}"
