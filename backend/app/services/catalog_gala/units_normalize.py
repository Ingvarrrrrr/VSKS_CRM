"""Нормализация степени единицы измерения — "мм2"→"мм²", "м3"→"м³",
"кг/м3"→"кг/м³", "м2/л"→"м²/л" — ОДНА функция для ВСЕХ конвертеров catalog_gala/
(ПРАВИЛО №6). Раньше жила только в from_electro_mpo.py и срабатывала только
когда степень — хвост ВСЕЙ строки единицы (полное совпадение regex);
baucenter_construction_all.json (владелец, 26.10) принёс составные единицы
вида "м2/л" ("Расход в один слой до (м2/л)"), где степень стоит не в конце
строки — поэтому здесь замена ГЛОБАЛЬНАЯ (re.sub по всем вхождениям
"<буква><2|3>", не только по полному совпадению)."""
import re

_SUPERSCRIPT_DIGITS = {"2": "²", "3": "³"}
# <буква><2|3>, не являющееся частью более длинного числа ("20", "35" и т.п.
# не трогаем — там цифра не показатель степени единицы).
_UNIT_POWER_RE = re.compile(r"([a-zA-Zа-яА-ЯёЁ])([23])(?!\d)")


def normalize_unit(unit):
    if not unit:
        return unit
    return _UNIT_POWER_RE.sub(lambda m: m.group(1) + _SUPERSCRIPT_DIGITS[m.group(2)], unit)
