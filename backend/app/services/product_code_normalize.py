"""Regex для поиска буквенно-цифрового КОДА (марка/модель) В ИСХОДНОМ ТЕКСТЕ
каталога — ПРАВИЛО №6, не второй нормализатор кодов, а ЗЕРКАЛО уже
существующей нормализации в app.services.product_name_signature._digit_tokens
(_KEEP_ALNUM_RE там убирает дефис/пробел МЕЖДУ буквенной и цифровой частью
кода — "ОП-2"="ОП 2"="оп2" для СРАВНЕНИЯ "тот же код", см. докстринг там).

Повод (владелец, 29.10.2026): «огнетушитель оп2» в каталоге и в подсказках
строки заявки не поднимал «Огнетушитель порошковый ОП-2» — required-токен
для поиска строился из ЭТОЙ ЖЕ нормализованной формы («оп2», без дефиса),
но искался как ЛИТЕРАЛЬНАЯ подстрока ПРЯМО В Product.name/article/
manufacturer (app.services.product_search._numeric_condition) — а там
дефис/пробел, который нормализация убрала, РЕАЛЬНО ЕСТЬ ("ОП-2"), поэтому
литеральное совпадение без разделителя не находило его вовсе.

Функция ниже строит regex, допускающий ТОТ ЖЕ разделитель (дефис/пробел),
НЕОБЯЗАТЕЛЬНО, НА КАЖДОЙ границе буква↔цифра нормализованного токена —
ровно там, где его могла убрать нормализация. Общая для ЛЮБОГО кода такого
вида (не только огнетушителей): "клоп1" → "КЛОП-1"/"КЛОП 1"/"КЛОП1",
"рс50" → "РС-50"/"РС 50"/"РС50", "ввг3х2" (если слитно без разделителя в
норм. токене) → совпадает и слитная, и "расставленная" запись. Токены без
смешения букв/цифр (голое число "125" — один сегмент) возвращаются БЕЗ
изменений (re.escape как раньше) — граница "125"/"1250" не ослабляется.

Используется ТОЛЬКО product_search.py (поиск по тексту каталога, через
_numeric_token_regex) — _digit_tokens/_model_code_tokens в
product_name_signature.py (сравнение «тот же код» между карточками) этот
модуль НЕ вызывают, им нужен голый нормализованный ключ для set-сравнения,
не regex для поиска по тексту (другая задача, см. докстринг там)."""
import re

# Сегмент — непрерывный буквенный ИЛИ цифровой кусок нормализованного токена
# (вход сюда уже alnum-only, без дефисов/пробелов — см. _KEEP_ALNUM_RE в
# product_name_signature.py). "х"/"x" внутри размеров (ВВГ3х2.5 → после
# _KEEP_ALNUM_RE цифры/точка уже разделены по-своему той функцией — здесь
# просто чередуем буквы/цифры, как они есть в токене).
_SEGMENT_RE = re.compile(r"[a-zа-яё]+|\d+", re.IGNORECASE)

# Разделитель, который нормализация МОГЛА убрать на границе буква↔цифра —
# дефис (после fold_brand_or_code варианты тире уже свёрнуты в ASCII '-') или
# один пробел/таб. Необязательный — слитная запись («ОП2») матчится тоже.
_SEPARATOR = r"[-\s]?"


def code_literal_regex(norm_token: str) -> str:
    """norm_token — нормализованный alnum-код (без разделителей). Возвращает
    ТЕЛО regex (без граничных lookaround — их добавляет вызывающая сторона,
    product_search._numeric_token_regex, одинаково для всех веток), которое
    совпадёт с тем же кодом в исходном тексте каталога независимо от того,
    был ли между буквой и цифрой дефис, пробел или ничего."""
    segments = _SEGMENT_RE.findall(norm_token)
    if len(segments) <= 1:
        return re.escape(norm_token)
    return _SEPARATOR.join(re.escape(seg) for seg in segments)
