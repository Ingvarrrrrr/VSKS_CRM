"""Правило «Ответственный исполнитель» — роль-слот, а не человек.

В subsidy_approvers строка с role_name «Ответственный исполнитель» задаёт
ТОЛЬКО позицию в цепочке согласования (порядок, признак is_default и т.д.).
ФИО для этой роли никогда не хранится фиксированным в настройках субсидии —
оно определяется по каждой закупке отдельно (ответственный исполнитель этой
конкретной закупки: assigned_user_id / автор служебной записки / явный выбор
на форме), поэтому в БД для такой строки full_name всегда должен быть
плейсхолдер-прочерк, а user_id — NULL.

Если бы здесь лежало живое ФИО, оно бы утекало во ВСЕ закупки субсидии
независимо от того, кто их реально ведёт (это и произошло: id=45/id=23,
см. миграцию __responsible_role_deanchor__ и SECURITY-заметку в задаче).
Поэтому роутеры, которые пишут/читают subsidy_approvers и собирают цепочку
согласования по закупке, обязаны прогонять role_name через
`is_responsible_role()` и никогда не доверять сохранённому full_name для
этой роли.
"""

RESPONSIBLE_ROLE_NAME = "Ответственный исполнитель"
RESPONSIBLE_PLACEHOLDER = "_________________"


def _normalize(text: str | None) -> str:
    return (text or "").strip().casefold().replace("ё", "е")


def is_responsible_role(role_name: str | None) -> bool:
    """True, если роль — тот самый «слот» «Ответственный исполнитель».

    Сравнение регистронезависимое, с обрезкой пробелов и нормализацией ё→е,
    чтобы «ответственный исполнитель», « Ответственный Исполнитель » и т.п.
    тоже считались этой ролью.
    """
    return _normalize(role_name) == _normalize(RESPONSIBLE_ROLE_NAME)


def is_blank_person_name(name: str | None) -> bool:
    """True, если ФИО пустое или это плейсхолдер-прочерк (только подчёркивания/пробелы)."""
    if not name:
        return True
    stripped = name.strip().strip("_").strip()
    return stripped == ""
