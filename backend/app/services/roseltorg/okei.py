def _normalize_unit_name(name: str) -> str:
    return (name or "").strip().lower().replace(".", "").replace("  ", " ").strip()


def okei_for_unit(unit_name: str | None) -> str | None:
    """Название единицы измерения позиции → код ОКЕИ, либо None, если
    единица не распознана (не выдумываем код, которого нет)."""
    if not unit_name:
        return None
    return _OKEI_BY_NAME.get(_normalize_unit_name(unit_name))
