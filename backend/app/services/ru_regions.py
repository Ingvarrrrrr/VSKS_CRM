# Индекс: normalize(canonical_name) → canonical_name, строится один раз на импорте
_REGION_INDEX: dict[str, str] = {_normalize(k): k for k in RU_REGIONS}
# Дополнить индекс алиасами (alias value уже должен быть в _REGION_INDEX или RU_REGIONS)
for _alias_norm, _canonical in _ALIASES.items():
    if _alias_norm not in _REGION_INDEX:
        _REGION_INDEX[_alias_norm] = _canonical


def get_region_info(region_name: str | None) -> dict | None:
    """Вернуть {'okato': '45000000000', 'district': 'Центральный федеральный округ'}
    для субъекта РФ, или None (спец-значения «Не определён» и т.п. — тоже None).

    Поиск устойчив к регистру, букве ё, видам тире и пробелам.
    """
    if not region_name:
        return None
    # 1. Точное совпадение (быстрый путь)
    entry = RU_REGIONS.get(region_name.strip())
    if not entry:
        # 2. Нормализованный поиск через индекс
        canonical = _REGION_INDEX.get(_normalize(region_name))
        if canonical:
            entry = RU_REGIONS.get(canonical)
    if not entry:
        return None
    return {"okato": okato11(entry[0]), "district": entry[1]}
