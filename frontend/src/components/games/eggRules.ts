// Чистая логика разрешения "яйцо долетело до конца жёлоба" для EggGame —
// единственное место этого правила (Правило №6), вынесено из eggGame.ts,
// чтобы покрыть юнит-тестом без canvas/DOM.
//
// Правильное правило (по жалобе владельца на "практически невозможно
// поймать"): яйцо разрешается РОВНО в момент, когда оно доезжает до
// последнего шага жёлоба. Если корзина стоит в этом жёлобе в этот момент —
// ИЛИ стояла там в любой момент во время последнего шага (grace-окно
// длиной в один шаг, чтобы ранний уход мыши прямо перед кадром резолва не
// превращал пойманное яйцо в промах) — яйцо считается ПОЙМАННЫМ. После
// этого решение окончательное: ничто не может превратить его обратно в
// промах (вызывающий код обязан сразу перевести яйцо в терминальный
// статус 'caught' и больше не пересчитывать его).

export type EggArrivalOutcome = 'caught' | 'broken'

/**
 * Шаг, на котором нужно ЗАПОМНИТЬ, что корзина стояла в нужном жёлобе —
 * последний шаг перед прибытием (step === totalSteps - 1). Проверять это
 * нужно каждый кадр (не только на тике шага), иначе grace-окно поймает
 * лишь один случайный момент внутри шага.
 */
export function isLastStep(step: number, totalSteps: number): boolean {
  return step === totalSteps - 1
}

/**
 * Разрешение прибытия яйца в конец жёлоба.
 * @param alignedAtArrival корзина стоит в нужном жёлобе в момент прибытия
 * @param wasAlignedDuringLastStep корзина стояла в нужном жёлобе хоть раз
 *        во время последнего шага (grace-окно)
 */
export function resolveEggArrival(
  alignedAtArrival: boolean,
  wasAlignedDuringLastStep: boolean,
): EggArrivalOutcome {
  return alignedAtArrival || wasAlignedDuringLastStep ? 'caught' : 'broken'
}
