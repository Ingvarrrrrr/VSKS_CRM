"""Карточка казначейства (владелец, 27.10.2026): «не для всех полей из карточек
казначейства есть поле в карточке контрагента — должно быть для всех. ФИО
руководителя — каждая часть отдельно».

Строим in-memory .docx по образцу двух реальных карточек владельца (ЗО и ДНР —
не кладём сами файлы в репозиторий, только воспроизводим структуру их таблиц:
два столбца «поле / значение», лицевой счёт либо внутри строки банка (ЗО:
«...(л/сч 712ZUU57001)»), либо отдельной строкой (ДНР: «Лицевой счёт»),
ОКВЭД и казначейский счёт ДНР — в одной ячейке, двумя строками через перенос).

ПРАВИЛО №6: единственный парсер — app.services.contractor_file_parsing.
_parse_file_to_rows (используется /parse-file, /import/preview, /import/mapped) —
тестируем его напрямую, без HTTP и без БД.
"""
from io import BytesIO

from docx import Document

from app.services.contractor_file_parsing import _parse_file_to_rows


def _build_card_docx(rows: list[tuple[str, str]]) -> bytes:
    """Собрать .docx с одной таблицей «поле/значение» — как в карточках
    казначейства владельца (каждая строка — tbl.rows[i].cells[0]/[1])."""
    doc = Document()
    doc.add_paragraph("Учетная карточка организации")
    table = doc.add_table(rows=0, cols=2)
    for key, val in rows:
        row = table.add_row()
        row.cells[0].text = key
        row.cells[1].text = val
    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _as_dict(all_rows) -> dict:
    headers, values = all_rows[0], all_rows[1]
    return dict(zip(headers, values))


# ── Карточка «ЗО» — лицевой счёт внутри строки банка ────────────────────────

def test_treasury_card_zo_pattern_full_extraction():
    content = _build_card_docx([
        ("Полное наименование организации",
         "ЗАПОРОЖСКОЕ РЕГИОНАЛЬНОЕ ОТДЕЛЕНИЕ ВСЕРОССИЙСКОЙ ОБЩЕСТВЕННОЙ "
         "МОЛОДЕЖНОЙ ОРГАНИЗАЦИИ «ВСЕРОССИЙСКИЙ СТУДЕНЧЕСКИЙ КОРПУС СПАСАТЕЛЕЙ»"),
        ("Юридический адрес", "обл. Запорожская, г.о. Бердянск, пер. Металлистов, д. 5"),
        ("Фактический (почтовый) адрес", "обл. Запорожская, г.о. Бердянск, пер. Металлистов, д. 5"),
        ("Телефон/факс", "+79040926698"),
        ("Сайт организации", "https://vsks.ru/"),
        ("E-mail организации", "vsks85@vsks.ru"),
        ("Инн", "9001023381"),
        ("Кпп", "900201001"),
        ("Огрн, дата регистрации", "1239000013449, 13.12.2023"),
        ("Окпо", "81097794"),
        ("Наименование банка, местонахождение банка",
         "ОКЦ № 6 ЮГУ Банка России//УФК по Запорожской области, (л/сч 712ZUU57001)"),
        ("Казначейский счет", "03225643230000007001"),
        ("Бик", "042368903"),
        ("Единый казначейский счет", "401028105453 70000097"),
        ("Руководитель организации", "Юрченкова Анастасия Евгеньевна"),
        ("Должность", "Председатель совета"),
        ("Действует на основании", "Устава"),
    ])
    all_rows, hdr_idx = _parse_file_to_rows("card_zo.docx", content)
    assert hdr_idx == 0
    d = _as_dict(all_rows)

    assert d["Полное наименование"] == (
        "ЗАПОРОЖСКОЕ РЕГИОНАЛЬНОЕ ОТДЕЛЕНИЕ ВСЕРОССИЙСКОЙ ОБЩЕСТВЕННОЙ "
        "МОЛОДЕЖНОЙ ОРГАНИЗАЦИИ «ВСЕРОССИЙСКИЙ СТУДЕНЧЕСКИЙ КОРПУС СПАСАТЕЛЕЙ»"
    )
    # Короткого наименования в карточке нет — заполняется тем же значением,
    # что и «Полное наименование» (required-поле name не остаётся пустым).
    assert d["Наименование"] == d["Полное наименование"]
    assert d["Адрес"] == "обл. Запорожская, г.о. Бердянск, пер. Металлистов, д. 5"
    assert d["Почтовый адрес"] == "обл. Запорожская, г.о. Бердянск, пер. Металлистов, д. 5"
    assert d["Телефон организации"] == "+79040926698"
    assert d["Сайт"] == "https://vsks.ru/"
    assert d["Email организации"] == "vsks85@vsks.ru"
    assert d["ИНН"] == "9001023381"
    assert d["КПП"] == "900201001"
    assert d["ОГРН"] == "1239000013449"
    assert d["Дата регистрации"] == "13.12.2023"
    assert d["ОКПО"] == "81097794"
    # Лицевой счёт — извлечён из строки банка И убран из неё.
    assert d["Банк"] == "ОКЦ № 6 ЮГУ Банка России//УФК по Запорожской области"
    assert "712ZUU57001" not in d["Банк"]
    assert d["Лицевой счёт"] == "712ZUU57001"
    assert d["Казначейский счёт"] == "03225643230000007001"
    assert d["БИК"] == "042368903"
    # Перенос строки внутри номера счёта — склеен в одно число без пробела.
    assert d["Единый казначейский счёт"] == "40102810545370000097"
    assert d["Подписант"] == "Юрченкова Анастасия Евгеньевна"
    assert d["Должность"] == "Председатель совета"
    assert d["Основание"] == "Устава"
    # ФИО руководителя по частям.
    assert d["Фамилия подписанта"] == "Юрченкова"
    assert d["Имя подписанта"] == "Анастасия"
    assert d["Отчество подписанта"] == "Евгеньевна"


# ── Карточка «ДНР» — лицевой счёт отдельной строкой, ОКВЭД+казн.счёт в одной ячейке ──

def test_treasury_card_dnr_pattern_full_extraction():
    content = _build_card_docx([
        ("Полное наименование организации",
         "ДОНЕЦКОЕ РЕГИОНАЛЬНОЕ ОТДЕЛЕНИЕ ВСЕРОССИЙСКОЙ ОБЩЕСТВЕННОЙ "
         "МОЛОДЕЖНОЙ ОРГАНИЗАЦИИ «ВСЕРОССИЙСКИЙ СТУДЕНЧЕСКИЙ КОРПУС СПАСАТЕЛЕЙ»"),
        ("Юридический адрес",
         "283054, ДОНЕЦКАЯ НАРОДНАЯ РЕСПУБЛИКА, Г.О. ДОНЕЦК, Г. ДОНЕЦК, УЛ. ПУТИЛОВСКАЯ РОЩА, Д.4А"),
        ("Телефон/факс", "+79496106265"),
        ("Сайт организации", "https://vsks.ru/"),
        ("E-mail организации", "vsks80@vsks.ru"),
        ("Инн", "9304022845"),
        ("Кпп", "930901001"),
        ("Огрн, дата регистрации", "1239300015547, 16.11.2023"),
        ("Окпо", "81097794"),
        # Склеенная ячейка: «Казначейский счет» + «ОКВЭД 2» — две строки
        # внутри одной пары ключ/значение (перенос строки в ячейке Word).
        ("Казначейский счет\n\nОКВЭД 2", "03225643210000008201\n\n                                    94.99"),
        ("Наименование банка, местонахождение банка",
         "ОКЦ № 5 ЮГУ Банка России//УФК по Донецкой Народной Республике, г Донецк"),
        ("Единый Казначейский счет", "40102810745370000095"),
        ("БИК", "042157901"),
        ("Лицевой счет", "712ZU7L4002"),
        ("Руководитель организации", "Артеева Анна Игоревна"),
        ("Должность", "Председатель совета"),
        ("Действует на основании",
         "Решение исполнительного комитета всероссийской общественной молодёжной "
         "организации «всероссийский студенческий корпус спасателей» от 14 марта 2023 года"),
    ])
    all_rows, hdr_idx = _parse_file_to_rows("card_dnr.docx", content)
    assert hdr_idx == 0
    d = _as_dict(all_rows)

    assert d["ИНН"] == "9304022845"
    assert d["КПП"] == "930901001"
    assert d["ОГРН"] == "1239300015547"
    assert d["Дата регистрации"] == "16.11.2023"
    # Склеенная ячейка разбирается на два отдельных поля.
    assert d["Казначейский счёт"] == "03225643210000008201"
    assert d["ОКВЭД"] == "94.99"
    # Банк — без «(л/сч ...)» в этой карточке, лицевой счёт своей строкой.
    assert d["Банк"] == "ОКЦ № 5 ЮГУ Банка России//УФК по Донецкой Народной Республике, г Донецк"
    assert d["Единый казначейский счёт"] == "40102810745370000095"
    assert d["БИК"] == "042157901"
    assert d["Лицевой счёт"] == "712ZU7L4002"
    assert d["Подписант"] == "Артеева Анна Игоревна"
    assert d["Фамилия подписанта"] == "Артеева"
    assert d["Имя подписанта"] == "Анна"
    assert d["Отчество подписанта"] == "Игоревна"
    assert d["Основание"].startswith("Решение исполнительного комитета")
