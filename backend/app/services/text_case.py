"""capitalize_first — один источник капитализации строковых справочных полей
(ПРАВИЛО №6): категория закупки (purchase_categories.name) и свободнотекстовая
категория товара (Product.category) писались вперемешку то со строчной, то с
прописной буквы ("мебель" / "Мебель") — в справочнике заводились дубли,
различающиеся только регистром первой буквы. Единственная функция,
капитализирующая первую букву, остальное — как есть (не меняет регистр
остальных слов, акронимы/ФЭО-коды не трогает); вызывается везде, где это поле
принимает ввод пользователя или импорта.

Та же функция используется миграцией backend/alembic/versions/
6a570b9c50d5_capitalize_categories.py (импорт допустим — модуль не тянет ни
БД, ни настройки, см. докстринг миграции) — ОДИН источник правила и для
новых записей, и для разового бэкфилла старых (ПРАВИЛО №6).

Решение владельца 14.10.2026: «где в названиях категорий аббревиатуры и всё
большими буквами — не трогать, исправлять только там, где должно быть с
большой, а написано с маленькой». До этой правки capitalize_first делало
первую букву заглавной ВСЕГДА, из-за чего "лкп" превращалось в "Лкп" —
аббревиатура без гласных, которую нельзя "прочитать" как обычное слово.
"""

# Гласные, по которым отличаем обычное слово от аббревиатуры-акронима.
# Кириллица: все гласные русского алфавита. Латиница: aeiou + y (английское
# "y" часто читается как гласная — "by", "sky").
_CYRILLIC_VOWELS = set("аеёиоуыэюя")
_LATIN_VOWELS = set("aeiouy")
_VOWELS = _CYRILLIC_VOWELS | _LATIN_VOWELS

# Известные строчные аббревиатуры С гласной внутри, которые тем не менее
# нельзя капитализировать как обычное слово. Список пуст: на стенде такие
# случаи не встретились (проверено SELECT по purchase_categories.name и
# DISTINCT products.category 14.10.2026) — не выдумываем, добавляем сюда
# только то, что реально нашли в данных.
_KNOWN_LOWER_ABBREVIATIONS: set[str] = set()


def _leading_letters(value: str) -> str:
    """Первая "цепочка" букв строки — до первого не-буквенного символа
    (пробел, дефис, цифра, пунктуация). Нужна, чтобы у "it-оборудование"
    аббревиатуру проверяли только по "it", а не по всему слову с дефисом —
    у "оборудование" гласные есть, но это не делает "it" не-аббревиатурой."""
    run = []
    for ch in value:
        if ch.isalpha():
            run.append(ch)
        else:
            break
    return "".join(run)


def _is_abbreviation(word: str) -> bool:
    """Аббревиатура = слово из кириллицы/латиницы без единой гласной, длиной
    2-5 букв ("лкп", "сиз" — нет, у "сиз" есть "и"), либо слово, где
    заглавных букв больше одной (уже "СИЗ"/"IT" — капитализировать нечего).
    Пустое/однобуквенное слово — не аббревиатура (есть что капитализировать
    как обычную букву)."""
    if not word:
        return False
    lowered = word.lower()
    if lowered in _KNOWN_LOWER_ABBREVIATIONS:
        return True
    upper_count = sum(1 for ch in word if ch.isupper())
    if upper_count > 1:
        return True
    if 2 <= len(word) <= 5 and not any(ch in _VOWELS for ch in lowered):
        return True
    return False


def capitalize_first(value: str | None) -> str | None:
    """Первая буква — заглавная, ЕСЛИ она строчная И первое слово строки не
    похоже на аббревиатуру (ПРАВИЛО №6, решение владельца 14.10.2026).
    Остальное — без изменений, пробелы по краям убраны. None/пустая строка —
    вернёт None, чтобы вызывающий код мог единообразно проверить "пусто".

    Примеры: "мебель" -> "Мебель"; "лкп" -> "лкп" (аббревиатура, не трогаем);
    "СИЗ" -> "СИЗ" (первая буква уже заглавная); "it-оборудование" ->
    "It-оборудование" ("it" содержит гласную "i" — не аббревиатура)."""
    if value is None:
        return None
    trimmed = value.strip()
    if not trimmed:
        return None

    first_char = trimmed[0]
    if not first_char.isalpha() or not first_char.islower():
        # Не буква, либо уже заглавная (или регистронезависимый символ,
        # напр. цифра) — ничего менять не нужно.
        return trimmed

    leading_word = _leading_letters(trimmed)
    if _is_abbreviation(leading_word):
        return trimmed

    return trimmed[0].upper() + trimmed[1:]
