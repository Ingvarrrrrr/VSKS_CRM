export function normalizeOkeiUnit(raw?: string | null): string {
  if (!raw) return 'Штука'
  const trimmed = raw.trim()
  if (!trimmed) return 'Штука'
  const key = trimmed.toLowerCase()
  if (ALIASES[key]) return ALIASES[key]
  const cleanKey = key.replace(/\./g, '').trim()
  if (ALIASES[cleanKey]) return ALIASES[cleanKey]
  return trimmed
}

const names = ref<string[]>([])
let loaded = false
let loadingPromise: Promise<void> | null = null

async function loadOkeiUnits(): Promise<void> {
  if (loaded) return
  if (!loadingPromise) {
    loadingPromise = apiFetch<OkeiUnit[]>('/dictionaries/okei-units')
      .then((data) => {
        names.value = data.map((u) => u.name)
        loaded = true
      })
      .catch(() => {
        names.value = [...DEFAULT_OKEI_NAMES]
        loaded = true
      })
  }
  return loadingPromise
}

function isOkeiUnit(unit?: string | null): boolean {
  const v = (unit || '').trim()
  if (!v) return true
  const list = names.value.length ? names.value : DEFAULT_OKEI_NAMES
  return list.includes(v)
}

function unitSelectOptions(_current?: string | null): string[] {
  // Росэлторг поддерживает ТОЛЬКО список ОКЕИ. Неподдерживаемые единицы в список не добавляем!
  return names.value.length ? names.value : DEFAULT_OKEI_NAMES
}

export function useOkeiUnits() {
  void loadOkeiUnits()
  return { okeiUnitNames: names, isOkeiUnit, unitSelectOptions, normalizeOkeiUnit, loadOkeiUnits }
}
