"""Нормализация штрихкода товара (владелец, 27.10.2026, решение: штрихкод —
главный ключ сведения одной карточки товара из разных магазинов — см.
app/services/products_import_match.py, критерий (0.25)).

ЕДИНСТВЕННОЕ место разбора и проверки контрольной цифры штрихкода в проекте
(ПРАВИЛО №6) — используется products_import_apply.py (запись в
product_barcodes при импорте), products_import_match.py (критерий
сопоставления), scripts/merge_by_barcode.py.

Поддерживаемые форматы (по длине, только цифры): EAN-8 (8), UPC-12 (12),
EAN-13 (13), GTIN-14 (14). Контрольная цифра проверяется ОДНИМ общим
алгоритмом GS1 (одинаков для всех длин — весовые коэффициенты 3/1
чередуются от ПОСЛЕДНЕЙ цифры данных, т.е. считаются относительно позиции
контрольной цифры, а не от начала строки; поэтому дописывание незначащих
нулей СЛЕВА не меняет сумму и не портит проверку — см. ниже).

Канонизация (владелец, 27.10.2026, «чтобы один товар давал один ключ»):
  - UPC-12 (проверенный) → EAN-13 с ведущим нулём (0 + 12 цифр) — обычное
    представление того же товара в GS1 (US UPC = GS1 EAN с префиксом 0).
  - GTIN-14, начинающийся с '0' (проверенный) → EAN-13 (ведущий 0 отрезан) —
    тот же товар, просто дополненный до 14 знаков нулём слева.
  - GTIN-14 с НЕнулевой первой цифрой (индикатор упаковки) НЕ сворачивается —
    это другая единица учёта (упаковка, не единица товара), другой ключ.
  - EAN-8/EAN-13 (без ведущего 0 из GTIN-14) возвращаются как есть.

Невалидная контрольная цифра, неверная длина, нечисловой вход после
удаления всех нецифровых символов — None (штрихкод отбрасывается, не
участвует в сведении)."""
from typing import Optional

_VALID_LENGTHS = (8, 12, 13, 14)


def _only_digits(s) -> str:
    if s is None:
        return ""
    return "".join(ch for ch in str(s) if ch.isdigit())


def _check_digit_valid(digits: str) -> bool:
    """GS1 mod-10: цифры данных (все, кроме последней — контрольной),
    читаются с ПРАВОГО конца; первой (самой правой) цифре данных вес 3,
    далее вес чередуется 1/3. Контрольная цифра = (10 - sum%10) % 10. Один
    и тот же вид расчёта верен для EAN-8/UPC-12/EAN-13/GTIN-14 — GS1 General
    Specifications считает веса от позиции контрольной цифры, не от начала
    строки, поэтому длина кода не меняет формулу."""
    data = digits[:-1]
    check = int(digits[-1])
    total = 0
    for i, ch in enumerate(reversed(data)):
        weight = 3 if i % 2 == 0 else 1
        total += int(ch) * weight
    calc_check = (10 - total % 10) % 10
    return calc_check == check


def normalize_barcode(raw) -> Optional[str]:
    """Возвращает канонический штрихкод (строка только цифр, см. докстринг
    модуля про свёртку UPC-12/GTIN-14 в EAN-13) или None, если вход не похож
    на валидный штрихкод (неверная длина/контрольная цифра/нет цифр)."""
    digits = _only_digits(raw)
    if len(digits) not in _VALID_LENGTHS:
        return None
    if not _check_digit_valid(digits):
        return None

    if len(digits) == 12:
        return "0" + digits
    if len(digits) == 14 and digits[0] == "0":
        return digits[1:]
    return digits
