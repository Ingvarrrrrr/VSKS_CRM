// Единый хелпер: откладывает реактивное действие, вызванное ИЗНУТРИ обработчика
// события ApexCharts (dataPointSelection, click и т.п.), на следующий тик Vue.
//
// Причина (баг «TypeError: Cannot read properties of null (reading
// 'querySelectorAll')» в vue3-apexcharts 1.11.1, node_modules/vue3-apexcharts/
// dist/vue3-apexcharts.js): ApexCharts вызывает пользовательский колбэк
// СИНХРОННО изнутри собственного обработчика клика, который после вызова
// колбэка продолжает идти по forEach-у DOM-узлов графика (легенда, подсветка
// сегмента и т.п.). Если колбэк сразу меняет состояние так, что Vue
// размонтирует <apexchart> (v-if/Transition переключились, диалог со своим
// графиком открылся поверх, роутер увёл со страницы) — chart.destroy()
// выполняется СРАЗУ, DOM графика исчезает, и на следующей итерации своего
// forEach ApexCharts обращается к уже удалённому элементу → падение.
//
// nextTick() откладывает наше действие до момента, когда ApexCharts уже
// закончил свою синхронную обработку клика — к размонтированию это больше не
// гонка.
//
// Применять в КАЖДОМ обработчике chart.events.* (dataPointSelection, click),
// который может скрыть/заменить/убрать сам график: переключить v-if, открыть
// диалог, уйти роутером. Один механизм на все виджеты (ПРАВИЛО №6) — не
// заворачивать в nextTick в каждом файле по отдельности без этого хелпера.
import { nextTick } from 'vue'

export function deferChartAction(fn: () => void): void {
  nextTick(fn)
}
