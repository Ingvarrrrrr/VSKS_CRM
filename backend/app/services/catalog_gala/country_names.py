COUNTRY_KEY_NAMES = {
    "страна производитель",
    "страна производства",
    "страна изготовитель",
}


def norm_country_key(key_lower: str) -> str:
    """key_lower — ключ характеристики, уже в нижнем регистре. Схлопывает
    дефис в пробел и обрезает края, чтобы "страна-изготовитель" совпал со
    "страна изготовитель" из COUNTRY_KEY_NAMES."""
    return key_lower.replace("-", " ").strip()
