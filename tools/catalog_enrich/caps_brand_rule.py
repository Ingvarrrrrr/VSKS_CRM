"""Второе правило определения бренда Кувалды (владелец, 27.10.2026, после
находки: ~2190 строк, где manufacturer в исходном файле — ВТОРОЕ слово
названия, напр. "безударная" у "Дрель безударная сетевая ИНТЕРСКОЛ Д-10/420"
— is_bogus_manufacturer проверяет совпадение только с ПЕРВЫМ словом, такой
мусор не ловит. Решение владельца: исходному manufacturer Кувалды не
доверять вовсе, бренд для ВСЕХ строк собирается заново по двум правилам —
(1) словарь имени (brand_dictionary.py, целым словом/самое длинное
совпадение — проверяется первым), (2) это правило ниже, (3) иначе null.

Правило: Кувалда пишет бренд ЗАГЛАВНЫМИ буквами — первая ПОСЛЕ первого слова
названия последовательность из одного или нескольких ПОДРЯД идущих слов,
целиком в верхнем регистре (латиница ИЛИ кириллица), без цифр, не короче
2 букв, и не входящих в список стоп-слов ниже (технические
аббревиатуры/маркировки/материалы, которые тоже пишутся заглавными, но
брендом не являются). Слова ДО начала такой последовательности, которые не
подходят под условие, просто пропускаются при поиске её начала; первое слово
названия не проверяется никогда (бренд у Кувалды не стоит в начале)."""
import re
from typing import Optional

# Список стоп-слов — ОДНО место (владелец, 27.10.2026, по находкам на файле;
# дополнять по новым данным, не заводить второй список где-то ещё).
STOP_WORDS = {
    "ВСЕ", "ГОСТ", "LED", "USB", "DC", "AC", "SDS", "PLUS", "MAX", "PRO",
    "MINI", "УХЛ", "АКБ", "ЗУ", "РФ", "СИЗ", "НГ", "LS", "HD", "WI-FI",
    "GSM", "LCD", "RGB", "DIN", "ISO", "ЕАС", "EAC",
    # материалы
    "ПА", "ПП", "ПВХ", "ПЭ", "ПНД", "ПЭТ", "ПС", "ABS", "PVC", "PE", "PP",
    "НЖ", "AISI", "ПЭР",
    # владелец, 27.10.2026 (вторая правка) — родовые слова/коды/маркировки,
    # пойманные правилом 2 на реальных данных (частота ≥5), не бренды:
    #   CS/ATEX/ГСМ/ЩИТ/КАНАТ/ППТ — явно указаны владельцем;
    #   ДТ (дизельное топливо), HS (High Speed сталь), FR (fire retardant),
    #   SWL (safe working load — маркировка грузоподъёмности), АЗС, ВЛ
    #   (воздушная линия) — технические маркировки/единицы;
    #   ПРО/MASTER/SMART/ROBUST — родовые маркетинговые слова;
    #   НАБОР/КОМПЛЕКТ — родовые слова упаковки (по примеру владельца).
    "CS", "ATEX", "ГСМ", "ЩИТ", "КАНАТ", "ППТ",
    "ДТ", "HS", "FR", "SWL", "АЗС", "ВЛ",
    "ПРО", "MASTER", "SMART", "ROBUST",
    "НАБОР", "КОМПЛЕКТ",
}

_DIGIT_RE = re.compile(r"\d")
_LETTER_RE = re.compile(r"[A-Za-zА-Яа-яЁё]")
_STRIP_CHARS = "\"'«»().,;:!?"


def _qualifying_core(token: str) -> Optional[str]:
    """Возвращает "очищенное" слово (без обрамляющей пунктуации), если оно
    годится как часть ЗАГЛАВНОГО бренда, иначе None."""
    if _DIGIT_RE.search(token):
        return None
    core = token.strip(_STRIP_CHARS)
    if not core:
        return None
    # Владелец, 27.10.2026 (вторая правка): токен с хвостовым дефисом/точкой
    # ("КЭВ-" перед моделью "123", когда она записана через пробел) — это
    # обрезанный код, идущий перед моделью, а не часть бренда. Отбрасываем
    # целиком (не просто обрезаем символ) — "ТЕПЛОМАШ КЭВ-" → "ТЕПЛОМАШ".
    if core.endswith("-") or core.endswith("."):
        return None
    letters = _LETTER_RE.findall(core)
    if len(letters) < 2:
        return None
    if core.upper() in STOP_WORDS:
        return None
    if not core.isupper():
        return None
    return core


def find_caps_brand(name: str) -> Optional[str]:
    """Первая (после первого слова названия) максимальная подряд идущая
    последовательность слов-кандидатов ЗАГЛАВНЫМИ — см. докстринг модуля.
    Слова до начала последовательности, не прошедшие проверку, пропускаются;
    последовательность обрывается на первом не прошедшем проверку слове
    ПОСЛЕ того, как она уже началась."""
    if not name:
        return None
    tokens = name.split()
    if len(tokens) < 2:
        return None

    run: list[str] = []
    for tok in tokens[1:]:  # первое слово названия не участвует
        core = _qualifying_core(tok)
        if core:
            run.append(core)
        elif run:
            break
        # иначе — слово до начала последовательности, пропускаем и ищем дальше
    return " ".join(run) if run else None
