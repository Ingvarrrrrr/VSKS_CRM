// numberInput.ts — чистая функция очистки «сырого» ввода в числовое поле
// (Кол-во/Цена ед.) до пригодного для parseFloat вида. Единственное место
// (ПРАВИЛО №6), которым пользуется directives/numberOnly.ts — директива сама
// не содержит правил «что считать цифрой», только DOM-события.
//
// Владелец (29.10.2026): <v-text-field type="number"> пропускает в поле
// «Кол-во»/«Цена ед.» буквы e/E, +, -, а paste вставляет произвольный текст
// без проверки — v-model.number тихо превращал такое в NaN. Правило: цифры
// и РОВНО ОДИН разделитель дробной части (запятая нормализуется в точку —
// величина бывает дробной, м/кг); минус и экспонента недопустимы — количество
// и цена отрицательными не бывают.
export function sanitizeNumberInput(raw: string): string {
  if (!raw) return ''
  // Запятая — тоже разделитель дробной части (привычный ввод на русской
  // клавиатуре), нормализуем в точку до любой другой обработки.
  let s = raw.replace(/,/g, '.')
  // Всё, что не цифра и не точка, выбрасывается целиком (без минуса/e/+).
  s = s.replace(/[^0-9.]/g, '')
  // Только первая точка остаётся разделителем, остальные — не разделители,
  // просто удаляются (а не сдвигают дробную часть).
  const firstDot = s.indexOf('.')
  if (firstDot !== -1) {
    s = s.slice(0, firstDot + 1) + s.slice(firstDot + 1).replace(/\./g, '')
  }
  return s
}

// Один символ допустим как часть числа (используется directive'ой на
// beforeinput — проверка посимвольно для вставляемого e.data).
export function isAllowedNumberChar(ch: string): boolean {
  return /^[0-9.,]$/.test(ch)
}
