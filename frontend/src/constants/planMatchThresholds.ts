// planMatchThresholds — пороги классификации score из POST /feo-planned-items/match
// (владелец, 2026-09-16, задача «поиск по плановым позициям + массовая привязка»).
//
// Сам score считает ТОЛЬКО бэкенд (backend/app/services/text_match.py::score/
// generic_progressive_match, единственный движок сравнения имён, Правило №6) — здесь
// НЕ пересчитываем совпадение заново, только раскладываем уже посчитанное число по
// корзинам для UI (сортировка выпадающего списка на «точные/частичные/остальные»,
// подпись «точное совпадение» в диалоге массовой привязки). Числа зеркалят
// text_match.py (SCORE_AUTO=0.95, SCORE_SUGGEST=0.60) — при выборе кандидата с
// coverage=1.0 (все токены запроса совпали) generic_progressive_match отдаёт
// status='auto', отсюда EXACT берётся по самому строгому порогу (>=0.999, а не 0.95)
// — «точное совпадение» в диалоге показывается только когда имя совпало ЦЕЛИКОМ, а
// не «почти совпало». Если пороги в text_match.py когда-нибудь изменятся — поправить
// оба места одновременно (второго способа узнать порог на фронте нет, границы
// намеренно продублированы как константы, а не как алгоритм).
export const PLAN_MATCH_SCORE_EXACT = 0.999
export const PLAN_MATCH_SCORE_SUGGEST = 0.6
