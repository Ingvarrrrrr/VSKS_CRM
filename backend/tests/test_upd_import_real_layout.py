def test_nf110_find_code_row():
    found = find_upd_code_row(NF110_ROWS)
    assert found is not None
    code_row_idx, col = found
    assert code_row_idx == 4
    # 2026-10-02: наименование — под меткой '1а' в реальных файлах владельца,
    # не '1б' (см. _detect_upd_layout docstring).
    assert col["item_name"] == 2


def test_nf110_parse_items_and_total():
    code_row_idx, col = find_upd_code_row(NF110_ROWS)
    result = parse_upd_table(NF110_ROWS, code_row_idx, col)
    items = result["items"]
    assert len(items) == 2
    assert items[0]["item_name"] == "Изготовление жилетов"
    assert items[0]["quantity"] == 70.0
    assert items[0]["unit"] == "шт"
    assert items[0]["unit_price"] == 3000.0
    assert items[0]["total_price"] == 210000.0
    assert items[0]["vat_rate"] == "Без НДС"
    assert items[1]["item_name"] == "Доставка до адреса"
    assert items[1]["total_price"] == 12952.12
    total_sum = sum(it["total_price"] for it in items)
    assert round(total_sum, 2) == 222952.12
    # Строка «Всего к оплате» не должна попасть в items и не должна дать
    # ложное расхождение (sum по строкам == сумме в документе).
    assert not any(w.get("code") == "upd_total_mismatch" for w in result["warnings"])


def test_nf110_build_sheet_extra_offsets_correctly():
    extra = build_upd_sheet_extra(NF110_ROWS)
    assert extra is not None
    assert extra["is_upd"] is True
    assert extra["header_row_offset"] == 4
    assert extra["auto_mapping"]["item_name"] == 2
    assert extra["auto_mapping"]["quantity"] == 6
    assert extra["auto_mapping"]["unit_price"] == 7
    assert extra["auto_mapping"]["total_price"] == 12
    assert len(extra["preview"]) == 2


