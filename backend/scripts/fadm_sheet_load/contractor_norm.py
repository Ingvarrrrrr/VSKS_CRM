"""normalize_contractor_name — ПРЕД-нормализация перед app.services.
vehicle_org_matching.normalize_org_name (ПРАВИЛО №6: второй нормализатор НЕ
заводится, этот модуль только расширяет уже существующий перед вызовом).

БАГ, найденный на реальном CSV (владелец, 04.10.2026): normalize_org_name
снимает только УЖЕ СОКРАЩЁННЫЕ токены ОПФ (см. её _LEGAL_FORM_TOKENS —
"ооо"/"ао"/"пао"/"ип"/... единичными словами) — она НЕ разворачивает ПОЛНЫЕ
словесные формы («ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ „ДИАМАНТ-Д“» не
сворачивается к тому же значению, что и «ООО "ДИАМАНТ-Д"» — ровно тот
случай, что и дал пропущенного двойника на реальных данных). Также не знает
отдельные сокращения САО/СПАО (их нет в _LEGAL_FORM_TOKENS вообще) и не
чинит артефакт «слово- слово» (пробел после дефиса, без пробела перед ним) —
оба бага зафиксированы здесь же, а не в app/services/vehicle_org_matching.py
(инструкция задания: правки только в backend/scripts/fadm_sheet_load/).

ЭТО ПОТЕНЦИАЛЬНЫЙ БАГ ДЕДУПА КОНТРАГЕНТОВ В САМОМ ПРИЛОЖЕНИИ (не только в
этом скрипте) — normalize_org_name используется в find_or_create_contractor
и find_contractors_by_name (app/services/contractor_resolve.py), то есть
ЛЮБОЙ ввод с полной словесной ОПФ («Общество с ограниченной
ответственностью "Ромашка"») заведёт НОВОГО контрагента, даже если «ООО
"Ромашка"» уже есть в базе. Стоит завести отдельную задачу на правку
normalize_org_name — здесь это обойдено локальной пред-нормализацией, т.к.
app/* трогать запрещено условием текущей задачи.
"""
from __future__ import annotations

import re
from typing import Any

from app.services.vehicle_org_matching import normalize_org_name

_HYPHEN_WS_RE = re.compile(r"\s*-\s*")

# Полная форма → короткий токен, который normalize_org_name УЖЕ умеет снимать
# (её _LEGAL_FORM_TOKENS). Порядок важен: более длинные/специфичные формы
# проверяются раньше более общих («публичное акционерное общество» раньше
# «акционерное общество», иначе общая форма съест часть специфичной).
_FULL_FORM_TO_SHORT: tuple[tuple[str, str], ...] = (
    ("общество с ограниченной ответственностью", "ооо"),
    ("страховое публичное акционерное общество", "спао"),
    ("публичное акционерное общество", "пао"),
    ("непубличное акционерное общество", "ао"),
    ("страховое акционерное общество", "сао"),
    ("закрытое акционерное общество", "зао"),
    ("открытое акционерное общество", "оао"),
    ("акционерное общество", "ао"),
    ("индивидуальный предприниматель", "ип"),
    ("автономная некоммерческая организация дополнительного профессионального образования", "ано дпо"),
    ("автономная некоммерческая организация", "ано"),
    ("производственный кооператив", "пк"),
    ("крестьянское (фермерское) хозяйство", "кфх"),
)

# normalize_org_name НЕ знает эти сокращения (отсутствуют в _LEGAL_FORM_TOKENS
# целиком) — второй проход по словам уже нормализованной строки.
_EXTRA_SHORT_TOKENS = {"сао", "спао", "дпо"}


def normalize_contractor_name(raw: Any) -> str:
    """Контрагент → каноническая строка для точного сравнения (без fuzzy —
    lesson feedback_dedup_exact_only): полная ОПФ сворачивается к короткой
    ДО вызова normalize_org_name (которая сносит короткую форму и кавычки),
    артефакт «слово- слово»/«слово -слово» чинится до токенизации."""
    if not raw:
        return ""
    s = str(raw).strip().lower()
    # ё/е — прод-находка 04.10.2026 (ИП КЮНГ ФЕДОР/ФЁДОР): владелец печатает
    # и так и так вперемешку, normalize_org_name тоже не разводит эту пару.
    s = s.replace("ё", "е")
    s = _HYPHEN_WS_RE.sub("-", s)
    for full, short in _FULL_FORM_TO_SHORT:
        s = re.sub(rf"\b{re.escape(full)}\b", short, s)
    base = normalize_org_name(s)
    words = [w for w in base.split(" ") if w and w not in _EXTRA_SHORT_TOKENS]
    return " ".join(words).strip()
