"""Нормализация бренда / артикула производителя для СРАВНЕНИЯ (не для
показа человеку) — ЕДИНСТВЕННОЕ место (ПРАВИЛО №6, владелец, 27.10.2026):
`product_similar.py` (подсказка «похожие товары» для ручного слияния) и
`products_import_match.py` (автоматическое сведение карточки другого
магазина по бренду+артикулу производителя при импорте каталога) используют
ОДНУ эту функцию, вторую нормализацию не заводят.

Перенесено из product_similar.py (было `_fold`/`_SIMILAR_FOLD_MAP`/
`_SIMILAR_FOLD_TABLE`) при появлении второго потребителя той же
нормализации — сама таблица и её причина не менялись.

Та же таблица символ-в-символ, что и для точного сопоставления каталога
(гомоглифы кириллица/латиница, ё→е, пробелы/дефисы/кавычки,
app.services.product_catalog_match._CHAR_FOLD_MAP), НО БЕЗ цифро-буквенных
пар (0→о, 3→з, 4→ч) — владелец, 27.10.2026, прогон на проде: та свёртка 0→о
СЪЕДАЕТ хвостовые нули в коде модели/артикуле ("ОП-10"/"ОП-100" становились
«оп-1о»/«оп-1оо», т.е. после отбрасывания непохожих символов — ОДНО И ТО ЖЕ
"оп1" для 1/10/100 — разные товары слипались)."""
from app.services.product_catalog_match import _CHAR_FOLD_MAP, _WS_RE

_BRAND_CODE_FOLD_MAP = {k: v for k, v in _CHAR_FOLD_MAP.items() if k not in ("0", "3", "4")}
_BRAND_CODE_FOLD_TABLE = str.maketrans(_BRAND_CODE_FOLD_MAP)


def fold_brand_or_code(text) -> str:
    """Нормализует строку бренда или артикула производителя для сравнения
    (гомоглифы/регистр/пробелы схлопнуты, цифры не трогаются) — НЕ для
    показа человеку, показ использует исходное написание."""
    if not text:
        return ""
    folded = str(text).translate(_BRAND_CODE_FOLD_TABLE)
    return _WS_RE.sub(" ", folded.strip()).lower()
