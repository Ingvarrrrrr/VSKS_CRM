def as_dd_list(labels: Dict[str, str], sort_alpha: bool = False) -> List[Tuple[str, str]]:
    """(label, code) пары — для DataValidation / листа «Справочники» / выдачи
    списка полю «Тип ТС» в GET /api/vehicle-fields.

    sort_alpha=False (по умолчанию) — порядок словаря как есть, без изменений
    (поведение до 2026-09). Используется для STATE_LABELS/FUEL_TYPE_LABELS/
    PTS_KIND_LABELS — там порядок осознанный (состояние — от рабочего к
    списанному; топливо — по возрастанию марки; вид ПТС — 2 значения), алфавит
    его бы испортил, владелец сортировку для них не просил.

    sort_alpha=True — пары сортируются по подписи (см. ru_sort_key) ПЕРЕД
    добавлением «Нет данных». Владелец (2026-09): «Тип ТС» шёл вразнобой в
    выпадающих списках — отсортировать по алфавиту. Сортировка сделана именно
    здесь, при выдаче списка, а не переупорядочиванием TYPE_LABELS — коды и их
    соответствие подписям (используются в БД/имортпорте) трогать нельзя,
    порядок словаря — деталь реализации, не контракт.

    В обоих случаях в конец дописывается (NO_DATA_LABEL, None) — распоряжение
    владельца (2026-09): «Нет данных» обязан быть явным вариантом ОТВЕТА В
    ФАЙЛЕ для каждого поля с закрытым списком, включая эти четыре (тип ТС/
    состояние/топливо/вид ПТС), которых нет в правилах листа владельца
    (vehicle_sheet_dictionaries.py) — это собственные наборы системы. Код НЕ
    добавляется в сам словарь labels (TYPE_LABELS/STATE_LABELS/...) — «Нет
    данных» не становится новым состоянием/типом ТС в модели, это только
    пункт списка-подсказки на листе «Справочники»."""
    pairs = [(v, k) for k, v in labels.items()]
    if sort_alpha:
        pairs = sorted(pairs, key=lambda pair: ru_sort_key(pair[0]))
    return pairs + [(NO_DATA_LABEL, None)]


def label_to_code(labels: Dict[str, str], value: Optional[str]) -> Optional[str]:
    """Регистронезависимо превращает подпись (как в выпадающем списке) в код.

    «Нет данных» (см. is_no_data_text) — осознанный ответ «поле пусто», а не
    нераспознанный текст: возвращает None, в колонку не пишется, без warning'а
    (см. вызывающий код в vehicles_import.py). Любое другое значение, не
    найденное среди известных подписей, по-прежнему возвращается как есть
    (валидация Excel не блокирует нестандартный ввод, поэтому парсер тоже не
    должен его отбрасывать — просто сохранит текст пользователя).
    """
    if value is None:
        return None
    s = str(value).strip()
    if not s:
        return None
    if is_no_data_text(s):
        return None
    reverse = {label.strip().lower(): code for code, label in labels.items()}
    return reverse.get(s.lower(), s)


# ─────────────────────────── Свободный текст «Состояние» ────────────────────
#
# Дефект (Автоблок, актуализация 2026-08-31): в реальных файлах колонка
# «Состояние» заполняется произвольным текстом ("Рабочее", "На ходу. Пока на
# ходу", "Требует ремонта (г.Ростов-на-Дону)" и т.п.), который не совпадает ни
# с одной подписью STATE_LABELS дословно. Раньше label_to_code() в этом случае
# возвращала исходную строку как есть — она обрезалась до VARCHAR(20) и
# улетала в vehicles.state сырым текстом ("В надлежайщем состоя"), которое не
# совпадает ни с одним кодом (карточка ТС показывает «Неизвестно», фильтр по
# состоянию его не находит).
#
# Правило теперь: state — ТОЛЬКО один из 6 кодов STATE_LABELS либо NULL,
# никогда сырой текст. Нераспознанный/неточный текст классифицируется по
# ключевым словам (см. classify_state_keywords), а исходная формулировка
# целиком сохраняется в tech_condition_info — см. resolve_vehicle_state().

# Порядок ветвей ниже — приоритет ОТ более специфичного/терминального К общему:
#   1) utilized/destroyed — терминальные состояния списания; если текст вообще
#      их упоминает, это сильнее любых слов про "рабочее"/"ремонт" рядом.
#   2) needs_repair — "ремонт" + явный маркер потребности ("требуе-", "нужен")
#      важнее voda голого "ремонт", поэтому проверяется РАНЬШЕ in_repair.
#      Пример: «Нерабочее. Требуется ремонт.» — содержит и "нерабоч" (→broken)
#      и "требуется ремонт" (→needs_repair); needs_repair специфичнее и стоит
#      выше broken в порядке проверки, поэтому побеждает.
#   3) in_repair — голое "ремонт"/"ремонтир" без маркера потребности.
#      Пример: «В ремонте (г.Ростов-на-Дону), не на ходу» — содержит и
#      "в ремонте" (→in_repair), и "не на ходу" (→broken); in_repair
#      проверяется раньше broken, поэтому побеждает (машина в процессе
#      ремонта — более точный статус, чем просто «сломан»).
#   4) broken — "нерабоч"/"не на ходу"/"неисправ"/"сломан". Проверяется ДО
#      working, иначе "неисправно" (содержит корень "исправ") ушло бы в
#      working через голый корень "исправ".
#   5) working — самое общее/умолчательное состояние, проверяется последним.
#
# Опечатки исходника (Lesson: "надлежайщем" вместо "надлежащем" — переставлена
# буква "й") учтены укороченным корнем "надлежа" (без хвоста "-щем"/"-йщем") —
# он остаётся подстрокой обеих форм.
#
# "отличн" ("ОТЛИЧНОЕ"/"Отличное") и "необходим" ("Необходимо ТО и ремонт...")
# добавлены сверх исходного ТЗ по факту реального листа 26.05.2026 — это
# 2 из 13 реальных формулировок файла, не покрытые буквальным списком синонимов
# в задании ("рабоч"/"на ходу"/"исправ"/"надлежащ"/"норм" и "требу"/"нужен");
# без них 8 из 53 строк реестра остались бы нераспознанными, хотя смысл
# однозначен ("отличное состояние" = исправно; "необходим ремонт" = требуется).
_STATE_WORKING_ROOTS = ("рабоч", "на ходу", "исправ", "надлежа", "норм", "отличн")
_STATE_BROKEN_ROOTS = ("нерабоч", "не на ходу", "неисправ", "сломан")
_STATE_NEEDS_MARKERS = ("требу", "нужен", "нужна", "нужны", "необходим")


def classify_state_keywords(normalized_text: str) -> Optional[str]:
    """Классифицирует уже нормализованный (lower + collapsed spaces) текст
    состояния по ключевым словам/корням. Возвращает код STATE_LABELS или None,
    если ни одно правило не сработало (вызывающая сторона обязана в этом
    случае оставить state пустым — см. resolve_vehicle_state)."""
    s = normalized_text
    if not s:
        return None
    if "утилиз" in s:
        return "utilized"
    if "уничтож" in s or "списан" in s:
        return "destroyed"
    has_remont = "ремонт" in s
    if has_remont and any(marker in s for marker in _STATE_NEEDS_MARKERS):
        return "needs_repair"
    if has_remont:
        return "in_repair"
    if any(root in s for root in _STATE_BROKEN_ROOTS):
        return "broken"
    if any(root in s for root in _STATE_WORKING_ROOTS):
        return "working"
    return None


def resolve_vehicle_state(value: Optional[object]) -> Tuple[Optional[str], Optional[str]]:
    """Разбирает сырое значение колонки «Состояние» в (код, заметка_для_tech_info).

    - Точная подпись STATE_LABELS (регистронезависимо) → код, заметка не нужна.
    - Свободный текст, распознанный по ключевым словам (classify_state_keywords)
      → код; если в исходном тексте есть скобки — доп. сведения в скобках
      ("(г.Ростов-на-Дону)" — это место, а не состояние) переносятся в заметку,
      чтобы не потерялись.
    - Ничего не распознано → код None (state остаётся пустым), а исходный
      текст целиком уходит в заметку ("Состояние из файла: <текст>").

    Заметка адресована tech_condition_info — вызывающая сторона сама решает,
    как её туда домержить (не перезаписывая уже занесённые сведения).
    """
    if value is None:
        return None, None
    original = str(value).strip()
    if not original:
        return None, None
    if is_no_data_text(original):
        # Осознанный ответ «нет данных» — не «нераспознанный текст». В отличие
        # от остальной этой функции (которая ВСЕГДА сохраняет нераспознанный
        # текст в заметку), здесь заметка не нужна и предупреждение в
        # vehicles_import.py подниматься не должно — ведёт себя как пустая
        # ячейка (см. NO_DATA_LABEL, распоряжение владельца 2026-09).
        return None, None

    normalized = re.sub(r"\s+", " ", original).strip().lower()

    reverse_exact = {label.strip().lower(): code for code, label in STATE_LABELS.items()}
    exact_code = reverse_exact.get(normalized)
    if exact_code:
        return exact_code, None

    code = classify_state_keywords(normalized)
    if code is None:
        return None, f"Состояние из файла: {original}"

    if "(" in original:
        return code, f"Состояние из файла: {original}"

    return code, None
