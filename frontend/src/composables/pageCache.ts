// pageCache.ts — список главных страниц, которые App.vue держит живыми в
// <keep-alive> (план «мгновенный возврат на главные страницы», 2026-10-13).
//
// Имена ДОЛЖНЫ совпадать с именами компонентов, по которым keep-alive матчит
// через include: для <script setup> без явного defineOptions({ name }) Vite
// (@vitejs/plugin-vue) сам проставляет name по имени файла без расширения —
// проверено (grep `__name` в собранном чанке даёт ровно "DashboardView" и
// т.д.), поэтому здесь просто имена файлов views/*.vue.
//
// НЕ добавлять сюда CreateOrderView и прочие страницы форм/карточек — им
// кэш не нужен (разовый ввод, не «вернулись посмотреть»), и неограниченный
// список означает неограниченный рост памяти вкладки.
// Обычный (не readonly/as const) string[] — <keep-alive :include> в Vue
// типизирован как string | RegExp | (string | RegExp)[], readonly-тюпл
// сюда не подходит по типам.
export const CACHED_PAGE_NAMES: string[] = [
  'DashboardView',
  'SubsidiesView',
  'OrdersView',
  'WishesView',
  'MyTasksView',
]

// Максимум одновременно живых закэшированных страниц (LRU — Vue сам вытесняет
// самую давнюю неактивную при превышении). Пяти страницам из списка выше
// ровно впору — весь набор остаётся тёплым, лишние (например, при будущем
// расширении списка) не копятся бесконечно.
export const CACHED_PAGE_MAX = 5
