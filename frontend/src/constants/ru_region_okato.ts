/**
 * Найти RegionOkatoInfo по названию региона.
 * Устойчив к регистру, ё, видам тире, пробелам; понимает алиасы.
 */
export function resolveRegionOkato(name: string | null | undefined): RegionOkatoInfo | undefined {
  if (!name) return undefined
  // 1. Точное совпадение
  if (RU_REGION_OKATO[name.trim()]) return RU_REGION_OKATO[name.trim()]
  // 2. Через алиасы/нормализацию
  const normed = _norm(name)
  const canonical = _ALIASES[normed]
  if (canonical) return RU_REGION_OKATO[canonical]
  // 3. Перебор нормализованных ключей словаря
  for (const key of Object.keys(RU_REGION_OKATO)) {
    if (_norm(key) === normed) return RU_REGION_OKATO[key]
  }
  return undefined
}

export const RU_REGION_OKATO: Record<string, RegionOkatoInfo> = Object.fromEntries(
  ruRegionsData.map((r) => [r.name, { okato: r.okato, district: r.district }]),
)
