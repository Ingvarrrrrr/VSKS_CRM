/**
 * Русское склонение по числу — ЕДИНЫЙ источник (ПРАВИЛО №6). Раньше жило
 * приватной копией в relativeTime.ts; жалоба владельца 05.10.2026 (мастер
 * «Импорт факта»: «в 1 строках» — неверное склонение) показала, что копии
 * расползаются там, где текст составляется вручную. Новый текст со счётчиком
 * — через эту функцию, не руками.
 */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few
  return many
}

/** «в 1 строке» / «в 2 строках» / «в 5 строках» — предложный падеж слова
 *  «строка», используется во всех сводных предупреждениях мастеров импорта
 *  (StepRows/StepGroups), чтобы не плодить вручную «в N строках» с ошибкой
 *  склонения на единице. */
export function rowsInPhrase(n: number): string {
  return `в ${n} ${pluralRu(n, 'строке', 'строках', 'строках')}`
}
