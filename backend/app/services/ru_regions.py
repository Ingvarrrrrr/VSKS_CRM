def okato11(prefix: str) -> str:
    """ОКАТО субъекта → 11-значный код (WSDL okatoCode: \\d{11})."""
    return prefix.ljust(11, "0")


def _normalize(s: str) -> str:
    """Строка → нормализованный ключ: casefold, ё→е, тире→дефис, пробелы схлопнуть."""
    import re
    s = s.strip().casefold()
    s = s.replace("ё", "е")
    # все виды тире (en-dash U+2013, em-dash U+2014, minus U+2212, hyphen-minus) → обычный дефис
    s = re.sub(r"[\u2013\u2014\u2212\u00ad]", "-", s)
    # схлопнуть множественные пробелы
    s = re.sub(r"\s+", " ", s)
    return s


