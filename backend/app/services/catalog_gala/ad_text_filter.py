"""Фильтр рекламных предложений в description поставщика (владелец,
26.10.2026, решение дня по Задаче 1 после _strip_description_prefix) —
ЕДИНСТВЕННОЕ место, где текст очищается от рекламы магазина (ПРАВИЛО №6,
второй такой фильтр не заводить).

Повод: в fire_equipment_nomenclature.json у товаров «Гидроэлеватор пожарный
Г-600» и «Колонка пожарная КПА» всё description после срезки служебного
префикса "Описание ..." — чистая реклама магазина Magazin01 ("... по низким
ценам в Москве в компании Magazin01. На нашем сайте большой выбор... купить
... с доставкой по России."), без единого технического параметра товара; у
«ШКПС (шлем-каска пожарного спасателя) с пелериной (черная)» — тот же
паттерн ("по выгодным ценам в интернет-магазине Magazin01.ru. Продажа ... с
доставкой по всей России."). См. backend/tests/test_catalog_gala_ad_text_filter.py
— реальные тексты этих трёх товаров и фактический результат фильтра.

Алгоритм: текст разбивается построчно (перевод строки — всегда граница
между абзацами/группами предложений), внутри каждой строки — на предложения
по ".", "!", "?" с последующим пробелом или концом строки. Предложение,
содержащее (регистронезависимо, по подстроке) любой из маркеров
_AD_MARKERS, удаляется ЦЕЛИКОМ. Оставшиеся предложения строки склеиваются
обратно пробелом; строки — переводом строки. Если после фильтра ничего не
осталось — результат None (а не пустая строка), как и у остальных функций
очистки текста в этом пакете (clean_text/_strip_description_prefix).
"""
import re
from typing import Optional

# Маркеры рекламы магазина (владелец, 26.10.2026, источник решения — примеры
# товаров Г-600/КПА/ШКПС из fire_equipment_nomenclature.json, см. докстринг
# модуля). Подстрока, регистронезависимо.
#
# "продаж" (корень продажа/продаже/продажи) здесь БЫЛ и убран 27.10.2026
# (владелец, отчёт strip_ads_from_descriptions.py --apply на prod CSV,
# 213 519 товаров): ловил технические поля, где "продажи"/"продаже" — не
# реклама, а дата/срок — «Гарантийные обязательства: 1 год со дня продажи.»,
# «Срок гарантийного обслуживания: 2 года (с даты продажи)», «Распродажа:
# Нет» (атрибут "да/нет"), «Лидер продаж: Да», «Единица продажи», «В
# продаже с: 2018 года», «Количество единиц продаж в транспортной
# упаковке». Проверено на том же prod CSV: НИ ОДНО предложение, пойманное
# ТОЛЬКО этим корнем (без другого маркера рядом), не было рекламой магазина
# (см. _AD_MARKER_PATTERNS ниже — узкие формы вместо него; ШКПС/Г-600/КПА
# всё равно удаляются целиком через "с доставкой по"/"по низким ценам"/
# "в компании"/"интернет-магазин"/"magazin01", не через "продаж").
_AD_MARKERS = (
    "по низким ценам",
    "по выгодным ценам",
    "в компании",
    "интернет-магазин",
    "на нашем сайте",
    "с доставкой по",
    "купить",
    "осуществляем продажу",  # узкая форма вместо снятого корня "продаж" (27.10.2026)
    "magazin01",
    # Задача 2 (владелец, 2026-10-26, пример — пояс ППС-А):
    "в специализированном магазине",
    "магазине пожарной техники",
    "доставка по всей россии",
    "доставка по россии",
    "хотите заказать",
    "заказыва",  # корень: заказывайте/заказывать/заказывает
    "звони",  # корень: звоните/звонить
    "в наличии на складе",
    # Задача 3 (владелец, 2026-10-26, пример — «Широкий выбор
    # запорно-регулирующей арматуры...», 403 товара Магазин 01 /
    # К-Спасатель). Проверено на всём prod-каталоге (~215 тыс. товаров),
    # см. ad_filter_review.md — число удаляемых предложений и примеры по
    # каждому маркеру.
    "у нас большой выбор",  # "У нас большой выбор противопожарных средств..."
    "мы предлагаем широкий ассортимент",
    "в нашем каталоге представлены",
    "вы можете приобрести",  # "Здесь/Тут вы можете приобрести ..."
    "по доступной цене",
    "по доступным ценам",
    "мелким оптом",
    "скидк",  # корень: скидка/скидки/скидкой
    "гарантируем",
    "гарантия качества",
    "онлайн заказ",
    "доставка по рф",
    "во все регионы россии",  # "...с доставкой во все регионы России."/"Доставка во все регионы России."
)

# Маркеры-регулярные выражения (Задача 3) — применяются ко всему
# предложению целиком и привязаны к НАЧАЛУ предложения (^), а не к
# подстроке где угодно. Подстрока "широкий выбор"/"широкий ассортимент"
# встречается и в техническом тексте не в начале предложения — например,
# «Большой выбор диаметров и размеров, позволяющий подобрать...» (про сам
# товар, разные диаметры одной позиции) или «...защиты от падения
# широкого ассортимента применяемого на высоте оборудования» (про
# совместимость, а не про ассортимент магазина) — такие НЕ удаляются,
# т.к. "широкий выбор"/"широкий ассортимент" там не в начале предложения.
# "Широкий выбор по плавучести."/"по форме и плавающей способности" —
# тоже технический текст (про сам товар), явно исключены отрицательным
# просмотром вперёд.
#
# Узкие формы рекламы со словом "продажа"/"продаже"/"продажи" (27.10.2026,
# заменяют снятый широкий корень "продаж" выше) — найдены в реальных
# текстах prod CSV: "продажа ... с доставкой" (например «Продажа шлемов и
# касок ... с доставкой по всей России.» у ШКПС — для неё это резервный
# путь, предложение всё равно падает под "с доставкой по") и "продажа ...
# по ... ценам" (например «...продажа ... по оптовым ценам.»). Не привязаны
# к началу предложения (в отличие от "широкий выбор/ассортимент" ниже) —
# "продажа"/"цены"/"доставка" в рекламе магазина встречаются где угодно в
# предложении, не только в начале.
_AD_MARKER_PATTERNS = (
    re.compile(r"^широк\w*\s+выбор(?!\s+по\s+(?:плавучести|форме))"),
    re.compile(r"^широк\w*\s+ассортимент"),
    re.compile(r"продаж\w*.{0,80}?с\s+доставк"),
    re.compile(r"продаж\w*.{0,80}?по\b.{0,40}?цен"),
)

# Граница предложения внутри строки: ".", "!" или "?" (с повтором, "?!" и
# т.п.), за которым идёт пробел/конец строки.
_SENTENCE_BOUNDARY_RE = re.compile(r"(?<=[.!?])\s+")


def _split_into_sentences(line: str) -> list:
    line = line.strip()
    if not line:
        return []
    return [part.strip() for part in _SENTENCE_BOUNDARY_RE.split(line) if part.strip()]


def _is_ad_sentence(sentence: str) -> bool:
    lowered = sentence.lower()
    if any(marker in lowered for marker in _AD_MARKERS):
        return True
    return any(pattern.search(lowered) for pattern in _AD_MARKER_PATTERNS)


def strip_ad_sentences(text: Optional[str]) -> Optional[str]:
    """Удаляет рекламные предложения магазина из текста. См. докстринг
    модуля. Пустой/None вход и вход, где рекламными оказались все
    предложения, дают None."""
    if not text:
        return None

    kept_lines = []
    for line in text.split("\n"):
        sentences = _split_into_sentences(line)
        kept = [s for s in sentences if not _is_ad_sentence(s)]
        if kept:
            kept_lines.append(" ".join(kept))

    result = "\n".join(kept_lines).strip()
    return result or None
