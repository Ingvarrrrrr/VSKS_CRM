"""Общий механизм ранжирования «целое слово / первое слово» для поиска
каталога товаров (ПРАВИЛО №6) — ОДНА функция, применённая во ВСЕХ ветках
search_products (FTS-лестница _fetch_fts_page, OR-ослабление
_fetch_fts_page_or, старый containment-путь build_product_search_query/
_search_legacy_page) — вторую такую сортировку не писать.

Повод (владелец, 29.10.2026):
  - «масло 2х» находил первым кабель «Кабель силовой гибкий КГН 2х1,0 ...
    маслостойкий» — слово «масло» совпало как ЧАСТЬ «маслостойкий», «2х» —
    как ЧАСТЬ «2х1,0» (старый containment-путь, ILIKE '%масло%' AND
    '%2х%' в product_search._word_condition — подстрокой, без границы);
  - «вода» находил «Кондиционер для аквариумной воды»/«водо-ветроустойчивые
    спички»/«Водовозка» выше настоящей «Вода питьевая ...» — FTS-шаг строит
    tsquery с префиксом на последнем слове («вод:*»), который матчит ЛЮБОЕ
    слово, начинающееся на «вод» (водовозка, водоветроустойчивые), без
    бонуса за то, что слово запроса совпадает С ПЕРВЫМ СЛОВОМ названия
    целиком.

ОБЩЕЕ РЕШЕНИЕ — ДОПОЛНИТЕЛЬНЫЙ первый член ORDER BY (CASE DESC, выше —
лучше), который вызывающая сторона добавляет в САМОЕ НАЧАЛО своего
существующего списка сортировки (тип товара в начале названия/штраф
игрушек/бонус бренда/ts_rank/similarity — остаются ВТОРЫМ и далее уровнем,
см. вызовы в product_search.py):
  2 — ПЕРВОЕ слово названия стеммируется ТАК ЖЕ, как одно из слов запроса
      целиком (to_tsvector('russian', первое слово) @@ to_tsquery('russian',
      слово) — тот же стеммер Postgres russian, что и везде в проекте,
      Правило №6, свой стеммер не пишем; «вода»/«воды» — одна основа);
  1 — любое слово запроса встречается В НАЗВАНИИ ЦЕЛЫМ словом — граница по
      классу символов (не внутри другого слова и не внутри числового кода:
      «2х» не совпадает внутри «2х1,0», «масло» не совпадает внутри
      «маслостойкий»);
  0 — иначе (только часть слова/подстрока — прежнее поведение без этого
      бонуса, остальная лестница ORDER BY решает сама).

Слова короче 2 символов (предлоги/мусор) в сравнении не участвуют — как и
в остальном парсере запроса (product_query_parse.py). None, если ни одного
значимого слова не осталось — вызывающая сторона просто не добавляет term.
"""
import re
from typing import Sequence

from sqlalchemy import text

# Класс символов «часть слова» — тот же принцип границы, что в
# product_search._numeric_token_regex/product_code_normalize.code_literal_regex
# (там — граница КОДА с допуском разделителя между буквой и цифрой; здесь —
# граница ПРОСТОГО слова без такого допуска, нужен отдельный, более строгий
# паттерн для текстовых слов, не второй механизм на то же самое, а другая
# задача: не ослаблять «масло» до совпадения внутри «маслостойкий»).
_ALNUM_CLASS = "0-9a-zA-Zа-яёА-ЯЁ"


def _word_boundary_pattern(word: str) -> str:
    return rf"(?<![{_ALNUM_CLASS}]){re.escape(word)}(?![{_ALNUM_CLASS}])"


def significant_words(tokens: Sequence[str]) -> list[str]:
    """Разбирает токены (каждый — одно слово или фраза из нескольких слов,
    напр. бренд «Security Force») на отдельные слова от 2 символов —
    единый вход для word_match_rank_term ниже, вызывающая сторона не
    обязана заранее разбивать фразы."""
    out: list[str] = []
    for tok in tokens:
        out.extend(w for w in (tok or "").split() if len(w) >= 2)
    return out


def word_match_rank_term(
    tokens: Sequence[str],
    *,
    name_sql: str = "coalesce(name,'')",
):
    """CASE DESC term (2/1/0, см. docstring модуля) или None, если среди
    tokens не осталось ни одного значимого слова (меньше 2 символов —
    например запрос из одних предлогов/кодов-символов).

    ПЕРВЫЙ уровень (2) — ts_lexize('russian_stem', ...), НЕ
    to_tsvector/to_tsquery (QA-находка на синтетических товарах, 29.10.2026):
    to_tsvector('russian', 'Водо-ветроустойчивые спички') разбирает
    hyphen-compound на составные лексемы (парсер Postgres добавляет 'водо'
    КАК ОТДЕЛЬНУЮ лексему вдобавок к целой 'водо-ветроустойчив') — 'водо'
    стеммируется В ТУ ЖЕ основу 'вод', что и запрос «вода», и @@ (проверка
    на ВХОЖДЕНИЕ лексемы) ложно считает «Водо-ветроустойчивые...» первым
    словом, совпадающим с «вода». ts_lexize обращается ТОЛЬКО к словарю
    (без повторного разбора компаунда parser'ом) — стеммирует ПЕРВОЕ СЛОВО
    ЦЕЛИКОМ, как один токен, и «водо-ветроустойчивые» → {водо-ветроустойчив}
    — НЕ совпадает с «вода» → {вод}, при этом «воды» (падеж) → {вод} —
    совпадает, ровно то же поведение, что и до фикса, для настоящих форм
    слова."""
    words = significant_words(tokens)
    if not words:
        return None

    boundary_alt = "|".join(_word_boundary_pattern(w) for w in words)
    first_word_sql = f"split_part(btrim({name_sql}), ' ', 1)"

    params: dict = {"word_rank_boundary": boundary_alt}
    first_word_conditions = []
    for i, w in enumerate(words):
        param_name = f"word_rank_q{i}"
        params[param_name] = w.lower()
        first_word_conditions.append(
            f"ts_lexize('russian_stem', lower({first_word_sql})) "
            f"= ts_lexize('russian_stem', :{param_name})"
        )
    case_sql = "(CASE "
    if first_word_conditions:
        case_sql += f"WHEN {' OR '.join(first_word_conditions)} THEN 2 "
    case_sql += f"WHEN {name_sql} ~* :word_rank_boundary THEN 1 ELSE 0 END) DESC"
    return text(case_sql).bindparams(**params)
