// Единый источник истины (Правило №6) для лимита размера загружаемого файла
// и для человеко-читаемых сообщений об ошибках 413/414 при импорте.
//
// Баг владельца (2026-09-17): импорт в субсидию «Центрпоиск_3» падал с
// HTTP 414 (URI Too Long — слишком длинный URL, а не файл) без единого
// объяснения, и нигде в интерфейсе не было сказано, какой размер файла
// вообще допустим. Реальный предел размера ТЕЛА запроса задаёт nginx
// (`client_max_body_size 512m`, см. nginx/nginx.conf и
// deploy/edge/nginx.conf) — backend отдельных проверок размера не делает,
// поэтому 512 МБ здесь и есть настоящая граница, а не произвольное число.
//
// Существующие лимиты для фото/документов ТС (25 МБ, components/vehicles/*)
// и аватара сотрудника (3 МБ, StaffEditUserDialog.vue) — ДРУГИЕ ограничения
// (не про импорт списков), этот модуль их не переопределяет.
export const MAX_UPLOAD_SIZE_MB = 512
export const MAX_UPLOAD_SIZE_BYTES = MAX_UPLOAD_SIZE_MB * 1024 * 1024

/** Подпись «до N МБ» для подсказок под полем выбора файла — один текст на
 * все диалоги импорта, чтобы не разойтись в формулировке. */
export function uploadSizeHint(maxMb: number = MAX_UPLOAD_SIZE_MB): string {
  return `до ${maxMb} МБ`
}

/** Клиентская проверка размера ДО отправки — тот же лимит, что и у nginx,
 * чтобы человек не ловил голый HTTP 413 после долгой загрузки. Возвращает
 * текст ошибки или null, если файл в пределах лимита. */
export function checkUploadSize(file: File | null | undefined, maxMb: number = MAX_UPLOAD_SIZE_MB): string | null {
  if (!file) return null
  if (file.size > maxMb * 1024 * 1024) {
    const sizeMb = (file.size / (1024 * 1024)).toFixed(1)
    return `Файл слишком большой (${sizeMb} МБ). Максимальный размер — ${maxMb} МБ.`
  }
  return null
}

/** Человеко-читаемое сообщение для HTTP-статусов, специфичных для загрузки
 * файлов, — единственное место с этим текстом (Правило №6: не плодить
 * копии по каждому composable импорта). 413 отдаёт nginx при превышении
 * `client_max_body_size`, 414 — при слишком длинной строке запроса (см.
 * докстринг app/services/request_params.py на бэкенде: раньше туда
 * попадали параметры импорта, теперь они в теле формы, но старый фронт из
 * PWA-кеша ещё может ловить эту ошибку). Возвращает null для остальных
 * статусов — вызывающий код сам решает, что показать (обычно detail из
 * ответа сервера).*/
export function uploadHttpErrorMessage(status: number): string | null {
  if (status === 413) {
    return `Файл слишком большой. Максимальный размер — ${MAX_UPLOAD_SIZE_MB} МБ.`
  }
  if (status === 414) {
    return 'Слишком много позиций за один раз — запрос получился длиннее, чем допускает сервер. Повторите импорт: разбейте файл на части поменьше или обновите страницу (Ctrl+F5) и попробуйте снова — возможно, используется устаревшая версия приложения.'
  }
  return null
}
