def test_u1643_two_rows_10_percent_corrupted_cell_ignored():
    found = find_upd_code_row(U1643_ROWS)
    assert found is not None
    code_row_idx, col = found
    result = parse_upd_table(U1643_ROWS, code_row_idx, col)
    items = result["items"]
    assert len(items) == 2
    assert items[0]["unit"] == "шт"
    assert items[0]["unit_price"] == 82.0
    # total_price читается из колонки «9» (целая, "1 804,00"), а не из
    # повреждённой "5" ("1 640,0б0е") — повреждение там не должно давать
    # сбой парсинга итоговой суммы строки.
    assert items[0]["total_price"] == 1804.00
    assert items[1]["total_price"] == 462.00
    total_sum = round(sum(it["total_price"] for it in items), 2)
    assert total_sum == 2266.00
    assert not any(w.get("code") == "upd_total_mismatch" for w in result["warnings"])


def test_okei_translation():
    assert _okei_to_unit("796") == "шт"
    assert _okei_to_unit("") is None
    assert _okei_to_unit("--") is None
    assert _okei_to_unit("999999") is None


